    /// The variant names of `pub enum HookId { ... }` in the game's generated file.
    fn hook_id_variants(text: &str) -> Vec<String> {
        let start = text
            .find("pub enum HookId {")
            .expect("the file declares HookId")
            + "pub enum HookId {".len();
        let mut depth = 1usize;
        let end = text[start..]
            .char_indices()
            .find_map(|(offset, ch)| {
                match ch {
                    '{' => depth += 1,
                    '}' => depth -= 1,
                    _ => {}
                }
                (depth == 0).then_some(start + offset)
            })
            .expect("the enum closes");
        text[start..end]
            .split(',')
            .map(|variant| variant.trim().to_owned())
            .filter(|variant| !variant.is_empty())
            .collect()
    }

