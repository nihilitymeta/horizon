//! The hook table of the Lua host's generated bindings, as Rust source text.
//!
//! [`emit`] returns a whole file: the hook kinds and sides, the `HOOKS` table sorted by name (the
//! hooks the game's `HookId` names), `RENDER_HOOKS` with `is_render_hook`, and the lookups
//! `hook_info` (binary search) and `hook_id`. Nothing is written to disk here.

use std::collections::BTreeMap;

use crate::emit_impl::group_key;
use crate::ir::{HookIr, Ir, Kind, Side};

/// The fixed part of the file, before the table.
const PREAMBLE: &str = "
/// What a hook's listeners may do with its event.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum HookKind {
    Listen,
    Cancel,
    Collect,
    Replace,
}

/// Which side of the connection a hook runs on.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum HookSide {
    Client,
    Server,
    Both,
}

/// One hook of the surface, as the Lua host sees it. `HookId` is only `Clone` and `Copy`.
#[derive(Clone, Copy)]
pub struct HookInfo {
    pub name: &'static str,
    pub id: mod_api::HookId,
    pub kind: HookKind,
    pub side: HookSide,
    pub cancellable: Option<bool>,
}

/// The hooks the game's `HookId` names, sorted by name.
pub const HOOKS: &[HookInfo] = &[
";

/// The fixed part of the file, after the render hooks.
const LOOKUPS: &str = "\
/// The hook called `name`, if the surface has one and the game's `HookId` names it.
pub fn hook_info(name: &str) -> Option<&'static HookInfo> {
    HOOKS
        .binary_search_by(|hook| hook.name.cmp(name))
        .ok()
        .map(|index| &HOOKS[index])
}

/// The game's id of the hook called `name`, if the surface has one.
pub fn hook_id(name: &str) -> Option<mod_api::HookId> {
    hook_info(name).map(|hook| hook.id)
}

/// Whether `name` is one of `EMITTED`.
pub fn is_emitted(name: &str) -> bool {
    EMITTED.binary_search(&name).is_ok()
}
";

/// Converts a snake_case hook name to the CamelCase variant name of the game's `HookId`.
pub fn camel(name: &str) -> String {
    name.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

/// The whole generated file for `ir`. `emitted` names the hooks whose `Hooks` methods the
/// generated impl has (`EMITTED`); the same inputs always give the same text.
pub fn emit(ir: &Ir, emitted: &[&str]) -> String {
    let mut hooks: Vec<&HookIr> = ir.hooks.iter().collect();
    hooks.sort_by(|a, b| a.name.cmp(&b.name));
    let (render, named): (Vec<&HookIr>, Vec<&HookIr>) =
        hooks.into_iter().partition(|hook| hook.is_render());

    let mut out = format!(
        "// @generated by event-horizon-lua-gen from surface {}: do not edit.\n",
        ir.document_hash
    );
    out.push_str(PREAMBLE);
    for hook in named {
        out.push_str(&entry(hook));
    }
    out.push_str("];\n\n");
    out.push_str(&emitted_table(emitted));
    out.push_str(&render_table(&render));
    out.push_str(LOOKUPS);
    out
}

/// `hooks_coverage.txt` (issue 74, H3): one line per hook of the surface, sorted by name, `<hook>
/// emitted` or `<hook> skipped: <reason>`, under a header with the counts per reason. `emitted` names
/// the hooks with a method; `skipped` gives the reason of every other hook asked for.
pub fn coverage(ir: &Ir, emitted: &[String], skipped: &[(String, String)]) -> String {
    let mut hooks: Vec<&HookIr> = ir.hooks.iter().collect();
    hooks.sort_by(|a, b| a.name.cmp(&b.name));
    let reasons: BTreeMap<&str, &str> = skipped
        .iter()
        .map(|(name, reason)| (name.as_str(), reason.as_str()))
        .collect();
    let mut by_reason: BTreeMap<String, usize> = BTreeMap::new();
    let mut lines = String::new();
    let mut count = 0;
    for hook in &hooks {
        if emitted.contains(&hook.name) {
            count += 1;
            lines.push_str(&format!("{} emitted\n", hook.name));
        } else {
            let reason = reasons
                .get(hook.name.as_str())
                .copied()
                .unwrap_or("not emitted");
            *by_reason.entry(group_key(reason)).or_default() += 1;
            lines.push_str(&format!("{} skipped: {reason}\n", hook.name));
        }
    }
    let mut out = format!(
        "# Hook coverage (issue 74, H3) from surface {}, by event-horizon-lua-gen: do not edit.\n\
         # hooks: {}, emitted: {count}, skipped: {}\n",
        ir.document_hash,
        hooks.len(),
        hooks.len() - count
    );
    for (reason, n) in &by_reason {
        out.push_str(&format!("# skipped, {reason}: {n}\n"));
    }
    out.push('\n');
    out.push_str(&lines);
    out
}

/// `EMITTED` (the names with a generated `Hooks` method, sorted), the only hooks a mod may use.
fn emitted_table(emitted: &[&str]) -> String {
    let mut names: Vec<&str> = emitted.to_vec();
    names.sort_unstable();
    names.dedup();
    let mut out = String::from(
        "/// The hooks with a generated `Hooks` method, sorted by name: the ones a Lua mod may use.\n\
         pub const EMITTED: &[&str] = &[\n",
    );
    for name in names {
        out.push_str(&format!("    {name:?},\n"));
    }
    out.push_str("];\n\n");
    out
}

/// `RENDER_HOOKS` (the names) and `is_render_hook`, for the client-only render hooks.
fn render_table(render: &[&HookIr]) -> String {
    let mut out = String::from(
        "/// The client-only hooks of the render crate, sorted by name. The game's `HookId`\n\
         /// names none of them.\n\
         pub const RENDER_HOOKS: &[&str] = &[\n",
    );
    for hook in render {
        out.push_str(&format!("    {:?},\n", hook.name));
    }
    out.push_str(
        "];\n\n\
         /// Whether `name` is one of `RENDER_HOOKS`.\n\
         pub fn is_render_hook(name: &str) -> bool {\n    \
             RENDER_HOOKS.binary_search(&name).is_ok()\n}\n\n",
    );
    out
}

fn entry(hook: &HookIr) -> String {
    format!(
        concat!(
            "    HookInfo {{\n",
            "        name: {:?},\n",
            "        id: mod_api::HookId::{},\n",
            "        kind: HookKind::{},\n",
            "        side: HookSide::{},\n",
            "        cancellable: {},\n",
            "    }},\n",
        ),
        hook.name,
        camel(&hook.name),
        kind_name(hook.kind),
        side_name(hook.side),
        cancellable_text(hook.cancellable),
    )
}

fn kind_name(kind: Kind) -> &'static str {
    match kind {
        Kind::Listen => "Listen",
        Kind::Cancel => "Cancel",
        Kind::Collect => "Collect",
        Kind::Replace => "Replace",
    }
}

fn side_name(side: Side) -> &'static str {
    match side {
        Side::Client => "Client",
        Side::Server => "Server",
        Side::Both => "Both",
    }
}

fn cancellable_text(cancellable: Option<bool>) -> &'static str {
    match cancellable {
        Some(true) => "Some(true)",
        Some(false) => "Some(false)",
        None => "None",
    }
}

