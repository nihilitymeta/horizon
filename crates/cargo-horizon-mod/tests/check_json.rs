//! `cargo horizon-mod check` as a process (issue 53): with `--json` its stdout
//! is exactly one JSON value, and the human notices go to stderr.
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

/// A fresh folder of this test's own (tests run side by side, one process
/// each, but a leftover of an interrupted run is removed first).
fn scratch(test: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!(
        "cargo-horizon-mod-json-{test}-{}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// Runs the binary with `args`. `$MODKIT` is removed from its environment: a
/// lane sets it, and these tests are about a run with no checkout.
fn run(args: &[String]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_cargo-horizon-mod"))
        .args(args)
        .env_remove("MODKIT")
        .output()
        .unwrap()
}

fn args(list: &[&str]) -> Vec<String> {
    list.iter().map(|s| s.to_string()).collect()
}

/// A stand-in luau-lsp that reports only the unresolvable `@modkit` require
/// (the alias resolved against the mod, which sits in `dir/wand-mod`) and
/// fails, as the real one does with no modkit checkout.
#[cfg(unix)]
fn fake_luau_lsp(dir: &Path) -> PathBuf {
    use std::os::unix::fs::PermissionsExt;
    let unknown = dir.join("horizon-modkit/scripts/server/modkit.lua");
    let path = dir.join("fake-luau-lsp");
    std::fs::write(
        &path,
        format!(
            "#!/bin/sh\necho 'Unknown require: {}'\nexit 1\n",
            unknown.display()
        ),
    )
    .unwrap();
    std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755)).unwrap();
    path
}

/// The Lua template, generated by the binary itself.
fn lua_template(dir: &Path) -> PathBuf {
    let path = dir.join("wand-mod");
    let made = run(&args(&[
        "new",
        &path.display().to_string(),
        "--template",
        "lua",
    ]));
    assert!(
        made.status.success(),
        "{}",
        String::from_utf8_lossy(&made.stderr)
    );
    path
}

/// `--json` on a lua template with no modkit: stdout is one JSON object (no
/// notice line before it), `ok` is true, and the types step passes with its
/// detail saying `@modkit` was left unchecked. The notice goes to stderr.
#[cfg(unix)]
#[test]
fn json_check_without_a_modkit_prints_one_parseable_value() {
    let dir = scratch("no-modkit");
    let path = lua_template(&dir);
    let fake = fake_luau_lsp(&dir);
    let out = run(&args(&[
        "check",
        &path.display().to_string(),
        "--json",
        "--no-scripts",
        "--luau-lsp",
        &fake.display().to_string(),
        "--tools-cache",
        &dir.join("cache").display().to_string(),
    ]));
    let stdout = String::from_utf8_lossy(&out.stdout).into_owned();
    let stderr = String::from_utf8_lossy(&out.stderr).into_owned();
    assert!(out.status.success(), "stderr: {stderr}");
    let value: serde_json::Value = serde_json::from_str(&stdout)
        .unwrap_or_else(|e| panic!("stdout is not one JSON value ({e}): {stdout}"));
    assert_eq!(value["ok"], serde_json::Value::Bool(true), "{value}");
    let steps = value["steps"].as_array().expect("{value}");
    let types = steps
        .iter()
        .find(|s| s["name"] == "types")
        .expect("{value}");
    assert_eq!(types["status"], "pass", "{value}");
    let detail = types["detail"].as_str().unwrap_or_default();
    assert!(
        detail.contains("@modkit") && detail.contains("unchecked"),
        "{value}"
    );
    assert!(
        stderr.contains("@modkit requires are unchecked"),
        "{stderr}"
    );
    std::fs::remove_dir_all(&dir).unwrap();
}

/// `--modkit` naming no directory is an error that names the path, exit 1,
/// nothing on stdout: a typo does not silently skip the modkit's checks.
#[test]
fn a_modkit_flag_naming_no_directory_is_an_error_naming_it() {
    let dir = scratch("missing-modkit");
    let path = lua_template(&dir);
    let out = run(&args(&[
        "check",
        &path.display().to_string(),
        "--modkit",
        "/no/such",
    ]));
    assert_eq!(out.status.code(), Some(1));
    assert!(out.stdout.is_empty(), "{:?}", out.stdout);
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("/no/such"), "{stderr}");
    std::fs::remove_dir_all(&dir).unwrap();
}
