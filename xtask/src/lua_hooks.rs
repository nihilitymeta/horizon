/// One no-handler dispatch: the model only, no Lua work, outs unchanged.
fn quiet_block(model: &Model, tys: &BTreeMap<String, String>) -> String {
    let mut out = format!("    // {}: unregistered, nothing runs.\n", model.name);
    out.push_str("    {\n");
    emit_call(&mut out, model, tys, None, false);
    if model.contract == "cancel"
        && let Some(flag) = &model.cancel_flag
    {
        out.push_str(&format!(
            "    assert!(!{flag}, \"{flag} changed with no handler\");\n"
        ));
    }
    out.push_str("    }\n");
    out
}

/// Strip the `{name}: {kind}: ` prefix the classifier adds to a reason, so
/// the exposure doc (which has its own hook column) shows the reason itself.
fn exposure_reason(name: &str, kind: &str, reason: &str) -> String {
    let prefix = format!("{name}: {kind}: ");
    reason.strip_prefix(&prefix).unwrap_or(reason).to_owned()
}

/// The model's own reason a deferred hook is not exposable either: copied
/// from `model_of`'s classes, never rewritten (the fixed strings match the
/// rows the classifier emits for the same class elsewhere in this page).
fn deferred_model_reason(name: &str, class: &Class) -> String {
    match class {
        Class::Cannot(why) => why
            .split("; ")
            .map(|w| exposure_reason(name, "unsupported", w))
            .collect::<Vec<_>>()
            .join("; "),
        Class::Adapter(whys) => {
            let mut reasons: Vec<String> = whys
                .iter()
                .map(|w| exposure_reason(name, "adapter", w))
                .collect();
            reasons.sort();
            reasons.dedup();
            reasons.join("; ")
        }
        Class::Tick => "a `ticks` parameter (level-tick host)".to_owned(),
        Class::Handle(ty) => format!("a {ty} handle needs its own design"),
        Class::Protocol => "raw packets need their own design".to_owned(),
        Class::Generated(_) => {
            unreachable!("a deferred hook assessed as generated is exposable, not rejected")
        }
    }
}

/// The exposure-doc group of a cannot detail: deferred names kept by a
/// hand-written hook first, then the borrow kinds, then anything else.
fn cannot_group(detail: &str) -> &'static str {
    if detail.contains("hand-written hook keeps this name") {
        "deferred"
    } else if detail.contains("borrowed loot state") {
        "loot"
    } else if detail.contains("generating chunk") {
        "worldgen"
    } else if detail.contains("render state (render thread)") {
        "render"
    } else {
        "other"
    }
}

/// One exposure-doc section: the heading with its count, the section prose,
/// then one table row per hook, names sorted.
fn exposure_section(out: &mut String, heading: &str, prose: &str, rows: &mut [(String, String)]) {
    rows.sort();
    out.push_str(&format!("## {heading} ({})\n\n{prose}\n\n", rows.len()));
    out.push_str("| Hook | Reason |\n| --- | --- |\n");
    for (name, reason) in rows {
        out.push_str(&format!("| `{name}` | {reason} |\n"));
    }
    out.push('\n');
}

/// One classification line of the checked-in record: every hook in exactly
/// one class, so `--check` fails when a hook is in no class or classified
/// differently from what the model says now.
fn class_line(name: &str, class: &Class) -> String {
    let detail = match class {
        Class::Generated(_) => "generated".to_owned(),
        Class::Adapter(whys) => format!("adapter: {}", whys.join("; ")),
        Class::Tick => "tick: a `ticks` parameter (level-tick host)".to_owned(),
        Class::Cannot(why) => format!("cannot: {why}"),
        Class::Handle(ty) => format!("handle: {name}: a {ty} handle needs its own design"),
        Class::Protocol => format!("protocol: {name}: raw packets need their own design"),
    };
    format!("    (\"{name}\", \"{detail}\"),")
}

/// The generated `docs/api/hook-exposure.md`: every non-generated native
/// hook with its name, class and reason, grouped so a reader can tell a
/// deferral (#44) from a real exposure reason. Generated hooks are omitted:
/// they are the zero-hand-work event tables, one per native name.
fn exposure_doc(classes: &[HookClass], deferred: &[(String, Result<Model, Class>)]) -> String {
    let mut deferred_ok = Vec::new();
    let mut deferred_no = Vec::new();
    let mut deferred_unknown = Vec::new();
    let outcomes: BTreeMap<&str, &Result<Model, Class>> = deferred
        .iter()
        .map(|(name, outcome)| (name.as_str(), outcome))
        .collect();
    let mut render = Vec::new();
    let mut worldgen = Vec::new();
    let mut loot = Vec::new();
    let mut other = Vec::new();
    let mut adapter = Vec::new();
    let mut handle = Vec::new();
    let mut protocol = Vec::new();
    let mut tick = Vec::new();
    let mut generated = 0;
    for hc in classes {
        match &hc.class {
            Class::Generated(_) => generated += 1,
            Class::Adapter(whys) => {
                let mut reasons: Vec<String> = whys
                    .iter()
                    .map(|w| exposure_reason(&hc.name, "adapter", w))
                    .collect();
                reasons.sort();
                reasons.dedup();
                adapter.push((hc.name.clone(), reasons.join("; ")));
            }
            Class::Tick => tick.push((
                hc.name.clone(),
                "a `ticks` parameter (level-tick host)".to_owned(),
            )),
            Class::Cannot(why) => {
                let reasons: Vec<String> = why
                    .split("; ")
                    .map(|w| exposure_reason(&hc.name, "unsupported", w))
                    .collect();
                let row = (hc.name.clone(), reasons.join("; "));
                match cannot_group(why) {
                    // Deferred names split by what the model says: exposable
                    // (the deferral is the only reason) or rejected anyway
                    // (the row carries the model's own reason).
                    "deferred" => match outcomes.get(hc.name.as_str()) {
                        Some(Ok(_)) => deferred_ok.push(row),
                        Some(Err(class)) => deferred_no
                            .push((hc.name.clone(), deferred_model_reason(&hc.name, class))),
                        None => deferred_unknown.push(row),
                    },
                    "loot" => loot.push(row),
                    "worldgen" => worldgen.push(row),
                    "render" => render.push(row),
                    _ => other.push(row),
                }
            }
            Class::Handle(ty) => handle.push((
                hc.name.clone(),
                format!("a {ty} handle needs its own design"),
            )),
            Class::Protocol => protocol.push((
                hc.name.clone(),
                "raw packets need their own design".to_owned(),
            )),
        }
    }
    let mut out = String::from(
        "# Hook exposure\n\n<!-- GENERATED by `cargo run -p xtask -- lua-hooks`; do not edit. `--check` fails when this file is not what the classifier says. -->\n\nEvery native hook lands in exactly one class: `generated` (a zero-hand-work event table under the native name), `adapter` (a hand-written converter would unblock it), `handle` or `protocol` (a live handle or raw packets, each needing its own design), `tick` (the level-tick host the Lua runtime does not implement), or `cannot` (no event-table mapping exists, with the reason). `HOOK_CLASSIFICATION` in `crates/event-horizon-lua/src/generated_hooks/mod.rs` is the machine-readable record; this page is its human-readable form, so a hook is never silently missing from Lua: it is either generated or listed here with its reason.\n\n",
    );
    out.push_str(&format!(
        "{generated} hooks are generated and omitted below. The rest:\n\n"
    ));
    exposure_section(
        &mut out,
        "Deferred to #44 (name kept by a hand-written hook; would be exposable)",
        "These names stay with the hand-written hooks for now; removing the old hook is #44. The model says an event table could carry each of them, so the deferral is the only reason they are missing from Lua.",
        &mut deferred_ok,
    );
    exposure_section(
        &mut out,
        "Deferred to #44 AND not exposable",
        "These names stay with the hand-written hooks for now (removing the old hook is #44), and the model says no event-table mapping exists for them either. Each row carries the model's own reason, copied from the classifier, not rewritten.",
        &mut deferred_no,
    );
    if !deferred_unknown.is_empty() {
        exposure_section(
            &mut out,
            "Deferred to #44 (not assessed)",
            "These names stay with the hand-written hooks for now; the model could not assess them, so their exposability is unknown.",
            &mut deferred_unknown,
        );
    }
    exposure_section(
        &mut out,
        "Borrows render state (render thread)",
        "No event-table mapping exists: the argument is a render-thread borrow, and Lua runs on the game thread with no drawing API.",
        &mut render,
    );
    exposure_section(
        &mut out,
        "Borrows the generating chunk (worldgen)",
        "No event-table mapping exists: the argument borrows the chunk being generated.",
        &mut worldgen,
    );
    exposure_section(
        &mut out,
        "Borrowed loot state",
        "No event-table mapping exists: the argument is borrowed loot state.",
        &mut loot,
    );
    exposure_section(
        &mut out,
        "Borrowed client input",
        "No event-table mapping exists: the argument cannot enter the Lua state.",
        &mut other,
    );
    exposure_section(
        &mut out,
        "Adapter hooks",
        "Not event tables yet: a hand-written converter would unblock these.",
        &mut adapter,
    );
    exposure_section(
        &mut out,
        "Handle hooks",
        "Not event tables: a live handle only a design of its own can expose.",
        &mut handle,
    );
    exposure_section(
        &mut out,
        "Protocol hooks",
        "Not event tables: raw packets need their own design.",
        &mut protocol,
    );
    exposure_section(
        &mut out,
        "Tick-host hooks",
        "Not event tables: the Lua runtime does not implement the level-tick host.",
        &mut tick,
    );
    out
}

/// `rustfmt` over generated text, as a string: what write mode leaves in
/// the tree after `cargo fmt`, so `--check` compares the same bytes.
fn format_snippet(text: &str) -> Result<String, String> {
    use std::io::Write;
    use std::process::Stdio;
    let mut child = std::process::Command::new("rustfmt")
        .args(["--edition", "2024"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .map_err(|e| format!("rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("rustfmt has no stdin")?
        .write_all(text.as_bytes())
        .map_err(|e| e.to_string())?;
    let out = child.wait_with_output().map_err(|e| e.to_string())?;
    if !out.status.success() {
        return Err(String::from_utf8_lossy(&out.stderr).into_owned());
    }
    String::from_utf8(out.stdout).map_err(|e| e.to_string())
}

pub fn run(check: bool) -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let classes = classify(&root)?;
    let (mut generated, mut adapter, mut tick, mut cannot, mut handle, mut protocol) =
        (0, 0, 0, 0, 0, 0);
    let mut kinded = 0;
    for hc in &classes {
        match &hc.class {
            Class::Generated(m) => {
                generated += 1;
                if !matches!(m.kind, Kind::None) {
                    kinded += 1;
                }
            }
            Class::Adapter(_) => adapter += 1,
            Class::Tick => tick += 1,
            Class::Cannot(_) => cannot += 1,
            Class::Handle(_) => handle += 1,
            Class::Protocol => protocol += 1,
        }
    }
    println!(
        "lua-hooks: {generated} generated ({kinded} kind-filtered), {adapter} adapter, {handle} handle, {protocol} protocol, {tick} tick-host, {cannot} cannot-be-exposed ({} total)",
        classes.len()
    );

    let mut names = Vec::new();
    let mut kind_names = Vec::new();
    let mut invocations = Vec::new();
    let mut tests = Vec::new();
    let mut quiet = Vec::new();
    // Every visible field is asserted, or the generator fails naming the
    // hook and field. Spike hooks are hand-covered, except their generated
    // non-cancel test, which needs the same asserts; the generator still
    // scans each spike's own test body for the player-`name` assert below.
    // Optional-stack hooks check twice: the dispatch parity and the flipped
    // one, so both the present table and the absent nil are asserted.
    let spike_src = fs::read_to_string(
        root.join("crates/event-horizon-lua/src/generated_hooks/spike_tests.rs"),
    )
    .map_err(|e| e.to_string())?;
    let mut uncovered = Vec::new();
    let mut unasserted = Vec::new();
    let mut dups = Vec::new();
    for hc in &classes {
        let Class::Generated(model) = &hc.class else {
            continue;
        };
        let tys: BTreeMap<String, String> = model
            .dispatch_params
            .iter()
            .map(|p| (p.name.clone(), p.ty.clone()))
            .collect();
        names.push(model.name.clone());
        if !matches!(model.kind, Kind::None) {
            kind_names.push(model.name.clone());
        }
        invocations.push(invocation(model, &tys));
        let spike = SPIKE_HOOKS.contains(&model.name.as_str());
        if !spike {
            tests.push(test_fn(model, &tys));
        }
        // The second firing covers the optional-stack state the dispatch
        // index misses (odd is always nil): the name cannot collide with a
        // spike's hand-written test, so no hook is skipped.
        if has_opt_item(model) {
            tests.push(opt_item_test_fn(model, &tys));
        }
        // A hand-written spike test with a player table must assert the
        // `name` the table stands in for: the model checks below never see
        // the spike's own body.
        if spike {
            // The registered Lua as tokens: a commented-out assert, an
            // assert on another table's `name`, or the text inside a
            // string, is not the player's name. The gate needs the full
            // `event.<field>.name ==` sequence at a token boundary, outside
            // any string or comment.
            let lua = spike_test_body(&spike_src, &model.name).and_then(spike_lua);
            for field in &model.fields {
                if !matches!(field.conv, Conv::Player | Conv::PlayerOpt) {
                    continue;
                }
                if !lua.is_some_and(|lua| lua_asserts_player_name(lua, &field.name)) {
                    uncovered.push(format!("{}: {}.name", model.name, field.name));
                }
            }
        }
        // One firing's checks, at the dispatch parity and (for
        // optional-stack hooks) the flipped one.
        let mut check_firing = |flip_opt: bool| {
            for field in uncovered_fields(model, &tys, flip_opt) {
                uncovered.push(format!("{}: {field}", model.name));
            }
            for leaf in unasserted_leaves(model, &tys, flip_opt) {
                unasserted.push(format!("{}: {leaf}", model.name));
            }
            dups.extend(dup_values(model, &tys, flip_opt));
        };
        if model.contract == "cancel" {
            if model.cancel_flag.is_none() {
                uncovered.push(format!("{}: no cancel flag", model.name));
            } else {
                check_firing(false);
                if has_opt_item(model) {
                    check_firing(true);
                }
            }
            tests.push(no_cancel_test_fn(model, &tys));
        } else {
            if !spike {
                check_firing(false);
            }
            if has_opt_item(model) {
                check_firing(true);
            }
        }
        quiet.push(quiet_block(model, &tys));
        // Every hook proves an unregistered dispatch costs nothing; every
        // collect and replace hook proves two mods share the out in order.
        tests.push(cost_test_fn(model, &tys));
        if model.contract == "collect" || model.contract == "replace" {
            tests.push(duo_test_fn(model, &tys));
        }
    }
    if !uncovered.is_empty() {
        return Err(format!(
            "lua-hooks: no assertion for dispatch field(s): {} (assert every visible field, or allowlist it with a reason)",
            uncovered.join(", ")
        ));
    }
    // Every seeded leaf is asserted, or the generator fails naming the hook,
    // field and leaf: a seed the handler never checks still passes a runtime
    // that drops or renames it.
    if !unasserted.is_empty() {
        return Err(format!(
            "lua-hooks: table leaves with no assertion: {} (assert every seeded leaf)",
            unasserted.join(", ")
        ));
    }
    // Every asserted leaf carries its own value, or the generator fails
    // naming the hook, field and leaf: a repeated value passes when the two
    // leaves are swapped or one is zeroed.
    if !dups.is_empty() {
        return Err(format!(
            "lua-hooks: repeated assert value(s): {} (every asserted leaf needs its own value, so reordering or zeroing fails)",
            dups.join(", ")
        ));
    }

    let mut text = String::new();
    text.push_str(
        "//! The Lua side of every zero-hand-work native hook: one event table\n"
            .to_owned()
            .as_str(),
    );
    text.push_str(
        "//! per hook under the native name, over the hand-written runtime in\n//! `super::generated_runtime`. Do not edit: `cargo run -p xtask -- lua-hooks`\n//! regenerates this file, and `--check` fails when it is stale. Every\n//! native hook is classified exactly once below (`HOOK_CLASSIFICATION`),\n//! so a newly added native hook is either generated on re-run or fails the\n//! check naming it.\n\n",
    );
    text.push_str("/// Every native hook in exactly one class: `generated`, `adapter` +\n/// the missing converter, `tick` (the level-tick host), `cannot` + the\n/// reason. A new native hook lands here on re-run; `--check` fails until\n/// the file is regenerated, so the new hook is reviewed, not silently\n/// dropped. Only the classification test below reads it at runtime.\n");
    text.push_str("#[allow(dead_code)]\npub const HOOK_CLASSIFICATION: &[(&str, &str)] = &[\n");
    for hc in &classes {
        text.push_str(&class_line(&hc.name, &hc.class));
        text.push('\n');
    }
    text.push_str("];\n\n");
    text.push_str("#[cfg(test)]\nmod test_support;\n\n");
    text.push_str("#[cfg(test)]\nmod spike_tests;\n\n");
    text.push_str("#[cfg(test)]\nmod round3_tests;\n\n");
    text.push_str("/// The generated hooks, for `horizon.on`'s name check.\n");
    text.push_str("pub const GENERATED_HOOK_NAMES: &[&str] = &[\n");
    for name in &names {
        text.push_str(&format!("    \"{name}\",\n"));
    }
    text.push_str("];\n\n");
    text.push_str("/// The generated hooks whose `kind` filter runs: `horizon.on` rejects a\n/// kind for every other generated hook.\n");
    text.push_str("pub const GENERATED_KIND_HOOK_NAMES: &[&str] = &[\n");
    for name in &kind_names {
        text.push_str(&format!("    \"{name}\",\n"));
    }
    text.push_str("];\n\n");
    text.push_str("/// The `Hooks` methods: one macro invocation per hook (the table).\n");
    text.push_str("macro_rules! impl_generated_hooks {\n    () => {\n");
    for invocation in &invocations {
        text.push_str(invocation);
        text.push('\n');
    }
    text.push_str("    };\n}\n\n");
    text.push_str("#[cfg(test)]\nmod generated_tests {\n");
    text.push_str(
        "    use super::{GENERATED_HOOK_NAMES, GENERATED_KIND_HOOK_NAMES, HOOK_CLASSIFICATION};\n",
    );
    text.push_str("    use super::test_support::*;\n");
    text.push_str("    use horizon_client::mod_api::*;\n");
    text.push_str("    use horizon_client::item_data::StackData;\n");
    text.push_str("    use horizon_client::menu::AnvilCraft;\n");
    text.push_str("    use horizon_client::merchant::ItemCost;\n");
    text.push_str("    use horizon_world::consumable::UseAnimation;\n");
    text.push_str("    use std::time::Duration;\n\n");
    text.push_str("    #[test]\n    fn generated_classification_names_every_hook_once() {\n");
    text.push_str("        let mut seen = std::collections::HashSet::new();\n");
    text.push_str("        for (name, _) in HOOK_CLASSIFICATION {\n");
    text.push_str("            assert!(seen.insert(*name), \"{name} classified twice\");\n");
    text.push_str("        }\n");
    text.push_str("        for name in GENERATED_HOOK_NAMES {\n");
    text.push_str("            assert!(\n");
    text.push_str("                seen.contains(name),\n");
    text.push_str("                \"{name} generated but not classified\"\n");
    text.push_str("            );\n");
    text.push_str("        }\n");
    text.push_str("        for name in GENERATED_KIND_HOOK_NAMES {\n");
    text.push_str("            assert!(\n");
    text.push_str("                GENERATED_HOOK_NAMES.contains(name),\n");
    text.push_str("                \"{name} kind-filtered but not generated\"\n");
    text.push_str("            );\n");
    text.push_str("        }\n");
    text.push_str("    }\n\n");
    for test in &tests {
        for line in test.lines() {
            text.push_str("    ");
            text.push_str(line);
            text.push('\n');
        }
        text.push('\n');
    }
    text.push_str("    #[test]\n    fn generated_no_handler_does_no_lua_work() {\n");
    text.push_str("        const LUA: &str = \"-- nothing registered\";\n");
    text.push_str("        let (m, id, dir, lua) = loaded_tracked(\"gen_no_handler\", LUA);\n");
    text.push_str("        let firing_mods = boxed(m);\n");
    for block in &quiet {
        for line in block.lines() {
            text.push_str("    ");
            text.push_str(line);
            text.push('\n');
        }
    }
    // No handler was ever registered, so the witness never fired.
    text.push_str("        assert_eq!(witness(&lua), 0, \"no handler ran\");\n");
    text.push_str("        no_error(&id);\n");
    text.push_str("        drop_dir(dir);\n");
    text.push_str("    }\n");
    text.push_str("}\n");

    let path = root.join("crates/event-horizon-lua/src/generated_hooks/mod.rs");
    let doc_path = root.join("docs/api/hook-exposure.md");
    let deferred = deferred_outcomes(&root)?;
    let doc = exposure_doc(&classes, &deferred);
    if check {
        let current = fs::read_to_string(&path).map_err(|e| e.to_string())?;
        // Write mode formats after writing, so the check formats too:
        // otherwise every file disagrees with its own fresh output.
        let formatted = format_snippet(&text)?;
        if current != formatted {
            return Err(
                "generated_hooks/mod.rs is stale: re-run `cargo run -p xtask -- lua-hooks`".into(),
            );
        }
        let current_doc = fs::read_to_string(&doc_path).map_err(|e| e.to_string())?;
        if current_doc != doc {
            return Err(
                "docs/api/hook-exposure.md is stale: re-run `cargo run -p xtask -- lua-hooks`"
                    .into(),
            );
        }
        return Ok(());
    }
    fs::write(&doc_path, doc).map_err(|e| e.to_string())?;
    fs::write(&path, text).map_err(|e| e.to_string())?;
    // Format like the rest of the tree; failure here is loud, not silent.
    let status = std::process::Command::new("cargo")
        .args([
            "fmt",
            "-p",
            "event-horizon-lua",
            "--",
            "crates/event-horizon-lua/src/generated_hooks/mod.rs",
        ])
        .status()
        .map_err(|e| e.to_string())?;
    if !status.success() {
        return Err("cargo fmt failed on the generated file".into());
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{LuaTok, lex_lua, lua_asserts_player_name};

    #[test]
    fn player_name_assert_passes_the_gate() {
        assert!(lua_asserts_player_name(
            "horizon.on(\"x\", function(event)\n  assert(event.player.name == \"Alex\", \"name\")\nend)",
            "player"
        ));
        // Spacing around the dots and `==` does not matter: tokens do.
        assert!(lua_asserts_player_name(
            "assert(event.player.name==\"Alex\")",
            "player"
        ));
        assert!(lua_asserts_player_name(
            "assert(event . player . name == \"Alex\")",
            "player"
        ));
    }

    #[test]
    fn name_text_inside_a_string_is_not_an_assert() {
        // Bypass 1: the gate text inside a short string, double- or
        // single-quoted, with an escaped quote before it.
        assert!(!lua_asserts_player_name(
            "local s = \"event.player.name == \\\"Alex\\\"\"",
            "player"
        ));
        assert!(!lua_asserts_player_name(
            "local s = 'event.player.name == \\'Alex\\''",
            "player"
        ));
        // A real assert beside the string still passes.
        assert!(lua_asserts_player_name(
            "local s = \"event.player.name ==\"\nassert(event.player.name == \"Alex\")",
            "player"
        ));
    }

    #[test]
    fn name_text_inside_a_long_string_is_not_an_assert() {
        // Bypass 2: level-0 and level-1 long strings.
        assert!(!lua_asserts_player_name(
            "local s = [[event.player.name == \"Alex\"]]",
            "player"
        ));
        assert!(!lua_asserts_player_name(
            "local s = [=[event.player.name == \"Alex\"]=]",
            "player"
        ));
    }

    #[test]
    fn name_text_inside_a_comment_is_not_an_assert() {
        // Bypass 3: line comments and long comments of any level,
        // including a multiline level-1 block (only `--[[` was handled).
        assert!(!lua_asserts_player_name(
            "-- assert(event.player.name == \"Alex\")",
            "player"
        ));
        assert!(!lua_asserts_player_name(
            "--[[ assert(event.player.name == \"Alex\") ]]",
            "player"
        ));
        assert!(!lua_asserts_player_name(
            "--[=[\nassert(event.player.name == \"Alex\")\n]=]",
            "player"
        ));
    }

    #[test]
    fn a_longer_table_name_is_not_the_event() {
        // Bypass 4: no token boundary in a substring scan.
        assert!(!lua_asserts_player_name(
            "assert(not_the_event.player.name == \"Alex\")",
            "player"
        ));
        assert!(!lua_asserts_player_name(
            "assert(event.player.names == \"Alex\")",
            "player"
        ));
        // A different field's name does not satisfy this field.
        assert!(!lua_asserts_player_name(
            "assert(event.owner.name == \"Alex\")",
            "player"
        ));
    }

    #[test]
    fn dots_and_equals_lex_as_code() {
        // `..` is concat, not two field dots; a lone `=` is assignment.
        assert_eq!(
            lex_lua("a..b"),
            vec![LuaTok::Ident("a".to_owned()), LuaTok::Ident("b".to_owned())]
        );
        assert!(!lua_asserts_player_name(
            "event.player.name = \"Alex\"",
            "player"
        ));
    }
}
