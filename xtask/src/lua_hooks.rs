/// The bindings and dispatch call of one firing, without the Rust-side
/// asserts (the quiet K2/gone blocks and the non-cancel test use this).
fn emit_call(
    out: &mut String,
    model: &Model,
    tys: &BTreeMap<String, String>,
    kind_rust: Option<String>,
    flip_opt: bool,
) {
    let call = dispatch_call(model, tys, kind_rust, flip_opt);
    for binding in &call.bindings {
        out.push_str(binding);
        out.push('\n');
    }
    out.push_str(&call.call);
    out.push('\n');
}

/// The bindings, dispatch call and Rust asserts of one firing.
fn emit_firing(
    out: &mut String,
    model: &Model,
    tys: &BTreeMap<String, String>,
    kind_rust: Option<String>,
    flip_opt: bool,
) {
    emit_call(out, model, tys, kind_rust, flip_opt);
    for assert in rust_asserts(model, tys, flip_opt) {
        out.push_str(&assert);
        out.push('\n');
    }
}

