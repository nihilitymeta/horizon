//! Generates the Lua side of every zero-hand-work native hook: one event
//! table per hook under the native name, cancel via `horizon.cancel()`,
//! mutable/collect/replace values read back, `Flow`/`Option` answers.
//!
//! The checked-in `generated_hooks.rs` is a compact table (one macro
//! invocation per hook: name, host kind, event type, kind filter, field
//! name -> converter) over the hand-written runtime in
//! `generated_runtime.rs`, plus a model-derived smoke test per hook. The
//! tool's other half is the classification: EVERY native hook lands in
//! exactly one class (`generated`, `adapter` + the missing converter,
//! `tick` for the level-tick host, `cannot` + the reason), recorded in the
//! output's `HOOK_CLASSIFICATION`. `--check` fails when a hook is in no
//! class, is classified differently from what the model says now, or the
//! checked-in output is stale: a newly added native hook with only
//! supported field types is generated by re-running the tool, and one with
//! an unsupported field fails the check naming it.

use crate::lua_model::{
    Class, Conv, Host, Kind, Model, ReplaceRead, assert_lines, classify, lua_read, mutate_line,
    replace_sample, sample,
};
use std::{collections::BTreeMap, fs, path::Path};

// The smoke tests' kind filter: a zombie event fires zombie handlers only.
const KIND_ONE: &str = "minecraft:zombie";
const KIND_TWO: &str = "minecraft:skeleton";
// Entity ids the test host resolves: zombie, skeleton, gone.
const ENTITY_ONE: i64 = 11;
const ENTITY_TWO: i64 = 13;
const ENTITY_GONE: i64 = 99;

/// The macro's host kind for a model host.
fn host_ident(host: Host) -> &'static str {
    match host {
        Host::None => "none",
        Host::GameMut => "game_mut",
        Host::GameRef => "game_ref",
        Host::Level => "level",
        Host::LevelMut => "level_mut",
    }
}

/// The macro's kind filter for a model kind: one token tree, so the
/// contract macros take it as `$kind:tt`.
fn kind_tt(model: &Model) -> String {
    match &model.kind {
        Kind::None => "(none)".to_owned(),
        Kind::Field => "(field kind)".to_owned(),
        Kind::Entity { field, opt } => {
            if *opt {
                format!("(opt_entity {field})")
            } else {
                format!("(entity {field})")
            }
        }
    }
}

/// Whether a `&mut` parameter's value lives in the event struct (the trait
/// copies scalar `&mut`s in): only then do the seed and write-back skip the
/// dereference.
fn owned_mut_scalar(ty: &str) -> bool {
    matches!(
        ty.strip_prefix("&mut ").unwrap_or(""),
        "bool"
            | "i8"
            | "i16"
            | "i32"
            | "i64"
            | "u8"
            | "u16"
            | "u32"
            | "u64"
            | "f32"
            | "f64"
            | "usize"
            | "isize"
            | "i128"
            | "u128"
            | "char"
    )
}

/// The macro's seed tag for a field: the tag names the runtime arm, the
/// type only picks among the shapes a converter covers. `ty` is the field's
/// canonical native type from the model, `key` the struct key for `Struct`.
fn seed_tag(conv: &Conv, ty: &str, key: Option<&str>) -> String {
    match conv {
        Conv::Plain => {
            if ty.contains("String") || ty.contains("str") {
                "cloned"
            } else {
                "copy"
            }
        }
        Conv::PlainString => "cloned",
        Conv::OptPlain => "copy",
        Conv::Uuid => "uuid",
        Conv::OptUuid => "opt_uuid",
        Conv::Player => "player",
        Conv::PlayerOpt => "player_opt",
        Conv::Dim => "dim",
        Conv::Pos => "pos",
        Conv::PosStruct => "pos_struct",
        Conv::OptPos => "opt_pos",
        Conv::Chunk => "chunk",
        Conv::Pair => {
            if ty.contains("f64") {
                "pair64"
            } else {
                "pair"
            }
        }
        Conv::Vec3f => "vec3",
        Conv::IntSeq => "int_seq",
        Conv::StrSeq => "str_seq",
        Conv::Item => "item",
        Conv::OptItem => "opt_item",
        Conv::StateLevel => "state_level",
        Conv::StateGame => "state_game",
        Conv::BlockAtPos => "block_at_pos",
        Conv::BlockFromState => "block_from_state",
        Conv::MutScalar => {
            if owned_mut_scalar(ty) {
                "copy"
            } else {
                "copy_ref"
            }
        }
        Conv::MutString => "mut_string",
        Conv::MutOptString => "mut_opt_string",
        Conv::MutPos => "mut_pos",
        Conv::MutVec3 => "mut_vec3",
        Conv::MutPair => {
            if ty.contains("f64") {
                "mut_pair64"
            } else {
                "mut_pair"
            }
        }
        Conv::MutStrVec => "str_seq",
        Conv::Struct => return struct_shape(ty, key.unwrap_or("?")).0,
        Conv::Bytes => return "s_bytes".into(),
        Conv::PathStr => return "s_path".into(),
        Conv::TextVal => return "s_text".into(),
        Conv::TextOpt => return "s_opt_text".into(),
        Conv::PreLogin => return "s_defer".into(),
        Conv::StateProps => return "state_props_note".into(),
    }
    .to_owned()
}

/// The write-back tag for a mutable field: `None` transcribes no tag, and
/// the runtime's catch-all expands it to nothing. `ty` picks the dereference
/// like the seed does, `key` the struct shape for `Struct`.
fn write_tag(conv: &Conv, ty: &str, key: Option<&str>) -> Option<String> {
    match conv {
        Conv::MutScalar => Some(
            if owned_mut_scalar(ty) {
                "mut_scalar"
            } else {
                "mut_scalar_ref"
            }
            .to_owned(),
        ),
        Conv::MutString => Some("mut_string".into()),
        Conv::MutOptString => Some("mut_opt_string".into()),
        Conv::MutPos => Some("mut_pos".into()),
        Conv::MutVec3 => Some("mut_vec3".into()),
        Conv::MutPair => Some("mut_pair".into()),
        Conv::MutStrVec => Some(if ty.contains("str") {
            "mut_strvec_static".into()
        } else {
            "mut_strvec".into()
        }),
        Conv::Struct => struct_shape(ty, key.unwrap_or("?")).1,
        Conv::TextVal => Some("w_text".into()),
        Conv::TextOpt => Some("w_opt_text".into()),
        Conv::PreLogin => Some("w_defer".into()),
        _ => None,
    }
}

/// The macro's replace reader for an out shape.
fn read_tag(read: ReplaceRead, ret: &str) -> String {
    match read {
        ReplaceRead::Int | ReplaceRead::Bool => "value".into(),
        ReplaceRead::Pair => "pair".into(),
        ReplaceRead::Item => "item".into(),
        ReplaceRead::Struct => {
            format!("struct_out({})", replace_spelling(ret))
        }
        ReplaceRead::StructVec => {
            format!("struct_vec_out({})", replace_spelling(ret))
        }
        ReplaceRead::Bytes => "bytes_out".into(),
        ReplaceRead::AnswerState => "answer_state".into(),
    }
}

/// The native spelling of a replace out's converted type, for the macro's
/// type parameter.
fn replace_spelling(ret: &str) -> String {
    let norm: String = ret.chars().filter(|c| !c.is_whitespace()).collect();
    let inner = norm
        .strip_prefix("Option<")
        .and_then(|k| k.strip_suffix('>'))
        .unwrap_or(&norm);
    let inner = inner
        .strip_prefix("Vec<")
        .and_then(|k| k.strip_suffix('>'))
        .unwrap_or(inner);
    struct_spelling_inner(inner)
}

/// The macro's type parameter for a struct key: the resolving path, since
/// the expansion site (the hand-written Lua mod) names only what it
/// imports. Tuples of primitives and arrays resolve on their own; the one
/// named tuple with imports uses the runtime alias.
fn struct_spelling_inner(inner: &str) -> String {
    match inner {
        "Value" => "serde_json::Value".to_owned(),
        "Map" => "serde_json::Map<String, serde_json::Value>".to_owned(),
        "(String,Compound)" => "crate::generated_runtime::NamedTag".to_owned(),
        "(&'staticstr,&'staticstr)" => "(&'static str, &'static str)".to_owned(),
        "&'staticstr" => "&'static str".to_owned(),
        "UseAnimation" => "horizon_world::consumable::UseAnimation".to_owned(),
        "Duration" => "std::time::Duration".to_owned(),
        "SocketAddr" => "std::net::SocketAddr".to_owned(),
        "ItemCost" => "horizon_client::merchant::ItemCost".to_owned(),
        "AnvilCraft" => "horizon_client::menu::AnvilCraft".to_owned(),
        _ if inner.starts_with('[') || inner.starts_with('&') || inner.starts_with('(') => {
            inner.to_owned()
        }
        _ => format!("horizon_client::mod_api::{inner}"),
    }
}

/// The seed and write-back tags of a struct field: the key's wrapper picks
/// the sequence arm, the parameter type's borrow the value arm, and the
/// inner type is the runtime's type parameter.
fn struct_shape(ty: &str, key: &str) -> (String, Option<String>) {
    let norm: String = ty.chars().filter(|c| !c.is_whitespace()).collect();
    let seed = |arm: &str, inner: &str| format!("{arm}({})", struct_spelling_inner(inner));
    let write = |arm: &str, inner: &str| Some(format!("{arm}({})", struct_spelling_inner(inner)));
    fn inner_of(key: &str) -> &str {
        if let Some(k) = key.strip_prefix("Vec<").and_then(|k| k.strip_suffix('>')) {
            return k;
        }
        if let Some(k) = key.strip_prefix("&[").and_then(|k| k.strip_suffix(']')) {
            return k;
        }
        if let Some(k) = key
            .strip_prefix("Option<")
            .and_then(|k| k.strip_suffix('>'))
        {
            return k;
        }
        key
    }
    if key.starts_with("Vec<") {
        let inner = inner_of(key);
        return (seed("s_vec", inner), write("w_vec", inner));
    }
    if key.starts_with("&[") {
        let inner = inner_of(key);
        return (seed("s_slice", inner), None);
    }
    if key.starts_with("Option<") {
        let inner = inner_of(key);
        if norm.starts_with("&mut") {
            return (seed("s_opt", inner), write("w_optmut", inner));
        }
        return (seed("s_opt", inner), None);
    }
    match key {
        "NativeMapInfo" => ("s_mapinfo".into(), None),
        "NativeNoteBlockChange" => ("s_notechange".into(), None),
        "SoundPlayback" => ("s_sound".into(), None),
        _ => {
            if norm.starts_with("&mut") {
                (seed("s_mut", key), write("w_mut", key))
            } else if norm.starts_with('&') {
                (seed("s_ref", key), None)
            } else {
                (seed("s_val", key), None)
            }
        }
    }
}

/// The event type with its elided lifetimes, exactly as the trait carries
/// it, qualified: the expansion site names only what it imports.
fn event_ty(model: &Model) -> String {
    format!(
        "horizon_client::mod_api::{}{}",
        model.event, model.lifetimes
    )
}

/// One hook's method invocation: the generated table's compact entry.
fn extra_tags(model: &Model) -> Vec<String> {
    model
        .extras
        .iter()
        .map(|e| format!("{}: {}", e.name, seed_tag(&e.conv, "?", None)))
        .collect()
}

fn invocation(model: &Model, tys: &BTreeMap<String, String>) -> String {
    let contract = match model.contract.as_str() {
        "collect" => "gen_collect",
        "cancel" => "gen_cancel",
        "replace" => "gen_replace",
        _ => "gen_listen",
    };
    let mut tags: Vec<String> = model
        .fields
        .iter()
        .map(|f| {
            let ty = tys.get(&f.name).map(String::as_str).unwrap_or("?");
            let seed = seed_tag(&f.conv, ty, f.key.as_deref());
            match write_tag(&f.conv, ty, f.key.as_deref()) {
                Some(write) => format!("{}: {seed} => {write}", f.name),
                None => format!("{}: {seed}", f.name),
            }
        })
        .collect();
    tags.extend(extra_tags(model));
    let fields = tags.join(", ");
    let mut out = format!(
        "    {contract}!({}, {}, {}, {}, [{fields}]",
        model.name,
        host_ident(model.host),
        event_ty(model),
        kind_tt(model),
    );
    if let Some(o) = &model.out {
        // The return type names the converted shape, so it resolves where
        // the hand-written mod expands the table (structs live in `mod_api`,
        // not in its imports).
        let ret = match o.read {
            ReplaceRead::Struct => format!("Option<{}>", replace_spelling(&o.ret)),
            ReplaceRead::StructVec => {
                format!("Option<Vec<{}>>", replace_spelling(&o.ret))
            }
            _ => o.ret.clone(),
        };
        out.push_str(&format!(
            ", {} : {}, {}",
            o.name,
            read_tag(o.read, &o.ret),
            ret
        ));
    }
    out.push_str(");");
    out
}

/// A dispatch argument set: the `let mut` bindings (`&mut` parameters and
/// outs) and the call line. `kind_rust` overrides the kind source's value
/// (K1, K2, or gone) for kind-filtered hooks.
struct Call {
    bindings: Vec<String>,
    call: String,
}

fn dispatch_call(model: &Model, tys: &BTreeMap<String, String>, kind_rust: Option<String>) -> Call {
    let host_arg = match model.host {
        Host::None => String::new(),
        Host::GameMut => "&mut FakeHost::empty(), ".to_owned(),
        Host::GameRef => "&FakeHost::empty(), ".to_owned(),
        Host::Level => "&FakeLevel, ".to_owned(),
        Host::LevelMut => "&mut FakeLevel, ".to_owned(),
    };
    let mut bindings = Vec::new();
    let mut args = Vec::new();
    // Every native parameter in order; a non-collect out travels last.
    let mut params = model.dispatch_params.clone();
    if model.contract != "collect"
        && let Some(out) = &model.out
    {
        params.retain(|p| p.name != out.name);
    }
    for (n, param) in params.iter().enumerate() {
        let ty = param.ty.as_str();
        if Some(param.name.as_str()) == model.kind_field()
            && let Some(rust) = &kind_rust
        {
            args.push(rust.clone());
            continue;
        }
        if let Some(field) = model.fields.iter().find(|f| f.name == param.name) {
            let field_ty = tys.get(&field.name).map(String::as_str).unwrap_or(ty);
            let s = sample(&field.conv, field_ty, &field.name, n);
            if s.mutable {
                bindings.push(format!("    let mut {} = {};", param.name, s.rust));
                args.push(format!("&mut {}", param.name));
            } else if ty.trim_start().starts_with("&mut") {
                // A `&mut` sample with no write (an empty option): the
                // dispatch still needs a binding to borrow mutably.
                bindings.push(format!("    let mut {} = {};", param.name, s.rust));
                args.push(format!("&mut {}", param.name));
            } else {
                args.push(s.rust);
            }
        } else if model.skipped.contains(&param.name) {
            // The `name` a player table stands in for.
            args.push(sample(&Conv::Plain, ty, &param.name, n).rust);
        } else if ty.starts_with("BlockStateId") {
            // `is_bonemeal_success`'s `state`: kept out of the table (the
            // spike exposes it as `block`), still fired by dispatch.
            args.push(format!("BlockStateId({})", 8 + n));
        } else {
            args.push(format!("todo_{}", param.name));
        }
    }
    if model.contract == "cancel"
        && let Some(flag) = &model.cancel_flag
    {
        bindings.push(format!("    let mut {flag} = false;"));
        args.push(format!("&mut {flag}"));
    }
    if model.contract == "replace"
        && let Some(out) = &model.out
    {
        bindings.push(format!("    let mut {}: {} = None;", out.name, out.ret));
        args.push(format!("&mut {}", out.name));
    }
    let call = format!(
        "    dispatch_{}({host_arg}&firing_mods, {});",
        model.name,
        args.join(", ")
    );
    Call { bindings, call }
}

/// A kind-filtered test's firing plan: the K1/K2/gone dispatch arguments,
/// the kind the handler registers, and the kind the handler asserts (only a
/// `kind` string field asserts the kind; an entity id asserts its own
/// value through the normal field asserts).
struct KindPlan {
    k1: String,
    k2: String,
    gone: Option<String>,
    register: String,
    assert_kind: Option<String>,
}

fn kind_values(model: &Model) -> Option<KindPlan> {
    match &model.kind {
        Kind::None => None,
        Kind::Field => Some(KindPlan {
            k1: format!("\"{KIND_ONE}\""),
            k2: format!("\"{KIND_TWO}\""),
            gone: None,
            register: KIND_ONE.to_owned(),
            // The exact Lua literal, quotes included.
            assert_kind: Some(format!("\"{KIND_ONE}\"")),
        }),
        Kind::Entity { opt, .. } => {
            let (k1, k2) = if *opt {
                (format!("Some({ENTITY_ONE})"), format!("Some({ENTITY_TWO})"))
            } else {
                (ENTITY_ONE.to_string(), ENTITY_TWO.to_string())
            };
            let gone = if *opt {
                Some("None".to_owned())
            } else {
                Some(ENTITY_GONE.to_string())
            };
            Some(KindPlan {
                k1,
                k2,
                gone,
                register: KIND_ONE.to_owned(),
                // The entity id asserts as a number, without quotes.
                assert_kind: Some(ENTITY_ONE.to_string()),
            })
        }
    }
}

/// The handler body: an assert per field, the write-back edits, and the
/// cancel/replace answers.
fn handler_body(model: &Model, tys: &BTreeMap<String, String>, kind_lua: Option<&str>) -> String {
    let mut lines = Vec::new();
    // Param order, so the samples match the dispatch call's: the `name`
    // a player table stands in for still takes its index.
    for (n, param) in model.dispatch_params.iter().enumerate() {
        let Some(field) = model.fields.iter().find(|f| f.name == param.name) else {
            continue;
        };
        let ty = tys.get(&field.name).map(String::as_str).unwrap_or("?");
        let s = sample(&field.conv, ty, &field.name, n);
        if Some(field.name.as_str()) == model.kind_field()
            && let Some(kind) = kind_lua
        {
            lines.push(format!(
                "    assert({} == {kind}, \"kind\")",
                lua_read(&field.name)
            ));
        } else {
            lines.extend(assert_lines(
                &field.conv,
                &field.name,
                &s.lua,
                field.key.as_deref(),
                n,
            ));
        }
        if let Some(write) = s.write_lua {
            lines.push(mutate_line(&field.conv, &field.name, &write));
        }
    }
    if lines.is_empty() {
        // A handler with nothing to check still proves the event exists.
        lines.push("    assert(event ~= nil, \"event\")".to_owned());
    }
    if model.contract == "cancel" {
        lines.push("    horizon.cancel()".to_owned());
    }
    if let Some(out) = &model.out {
        let (rust, lua) = replace_sample(out.read, &out.ret, 0);
        let _ = rust;
        lines.push(format!(
            "    assert(event.{} == nil, \"replace seed\")",
            out.name
        ));
        lines.push(format!("    event.{} = {lua}", out.name));
    }
    for extra in &model.extras {
        lines.extend(assert_lines(
            &extra.conv,
            &extra.name,
            "\"minecraft:stone\"",
            None,
            0,
        ));
    }
    lines.join("\n")
}

/// The Rust asserts after the K1 dispatch: outs and write-backs reached the
/// native side.
fn rust_asserts(model: &Model, tys: &BTreeMap<String, String>) -> Vec<String> {
    let mut lines = Vec::new();
    if model.contract == "cancel"
        && let Some(flag) = &model.cancel_flag
    {
        lines.push(format!("    assert!({flag}, \"{flag} not cancelled\");"));
    }
    for (n, param) in model.dispatch_params.iter().enumerate() {
        let Some(field) = model.fields.iter().find(|f| f.name == param.name) else {
            continue;
        };
        let ty = tys.get(&field.name).map(String::as_str).unwrap_or("?");
        let s = sample(&field.conv, ty, &field.name, n);
        if let Some(write) = s.write_rust {
            lines.push(match &field.conv {
                Conv::MutStrVec => format!(
                    "    assert_eq!({0}, vec![\"test:edited\".to_owned(), \"test:seed2\".to_owned(), \"test:added\".to_owned()]);",
                    field.name
                ),
                Conv::PreLogin => format!("    assert_eq!({}.len(), 1);", field.name),
                // A bare `true`/`false` is a bool write-back: `assert!` reads
                // better and keeps clippy's `bool_assert_comparison` quiet.
                _ if write == "true" => format!("    assert!({});", field.name),
                _ if write == "false" => format!("    assert!(!{});", field.name),
                // Sequences compare through `Debug`: not every element
                // implements `PartialEq` (a spawn entry has none).
                _ if write.starts_with("vec![") => format!(
                    "    assert_eq!(format!(\"{{:?}}\", {}), format!(\"{{:?}}\", {write}));",
                    field.name
                ),
                _ => format!("    assert_eq!({}, {write});", field.name),
            });
        }
    }
    if let Some(out) = &model.out
        && model.contract == "replace"
    {
        let (rust, lua) = replace_sample(out.read, &out.ret, 0);
        match out.read {
            ReplaceRead::Item => {
                lines.push(format!(
                    "    let replaced = {}.expect(\"a replaced value\");",
                    out.name
                ));
                lines.push("    assert_eq!(&*replaced.item, \"test:result\");".to_owned());
                lines.push("    assert_eq!(replaced.count, 1);".to_owned());
            }
            ReplaceRead::AnswerState => {
                let _ = rust;
                let _ = lua;
                let state_idx = model
                    .dispatch_params
                    .iter()
                    .position(|p| p.name == "state")
                    .unwrap_or(0);
                lines.push(format!(
                    "    assert_eq!({}, Some(Some(BlockStateId({}))));",
                    out.name,
                    8 + state_idx
                ));
            }
            _ => lines.push(format!("    assert_eq!({}, Some({rust}));", out.name)),
        }
    }
    lines
}

/// One model-derived smoke test: a Lua handler asserts every field, edits
/// the mutable ones, and the Rust side checks the outs. Kind-filtered hooks
/// also prove a K2 (and gone) event does not fire them.
/// The spike's hand-specified tests cover these hooks; the model test
/// would collide with their names, so it skips them.
const SPIKE_HOOKS: &[&str] = &[
    "level_tick_pre",
    "chunk_load",
    "block_cook",
    "anvil_damaged",
    "player_container_close",
    "block_burn",
    "bell_ring",
    "arrow_loose",
    "block_lock_check",
    "component_types",
    "datapack_sync",
    "screen_tooltip",
    "is_bonemeal_success",
    "item_fluid_tank",
    "tooltip_component",
    "screen_click",
    "prepare_anvil",
];

fn test_fn(model: &Model, tys: &BTreeMap<String, String>) -> String {
    let mut out = format!("#[test]\nfn generated_{}() {{\n", model.name);
    match kind_values(model) {
        None => {
            let body = handler_body(model, tys, None);
            let lua = format!(
                "horizon.on(\"{}\", function(event)\n{body}\nend)",
                model.name
            );
            out.push_str(&format!(
                "    let (m, id, _dir) = loaded(\"gen_{}\", {lua:?});\n",
                model.name
            ));
            out.push_str("    let firing_mods = boxed(m);\n");
            let call = dispatch_call(model, tys, None);
            for binding in &call.bindings {
                out.push_str(binding);
                out.push('\n');
            }
            out.push_str(&call.call);
            out.push('\n');
            for assert in rust_asserts(model, tys) {
                out.push_str(&assert);
                out.push('\n');
            }
            out.push_str("    no_error(&id);\n");
        }
        Some(plan) => {
            let body = handler_body(model, tys, plan.assert_kind.as_deref());
            let lua = format!(
                "horizon.on(\"{}\", function(event)\n{body}\nend, \"{}\")",
                model.name, plan.register
            );
            out.push_str(&format!(
                "    let (m, id, _dir) = loaded(\"gen_{}\", {lua:?});\n",
                model.name
            ));
            out.push_str("    let firing_mods = boxed(m);\n");
            // K2 (and gone) must not fire the K1 handler: any assert would
            // trip `no_error`.
            for (label, kind_arg) in [("K2", Some(plan.k2)), ("gone", plan.gone)]
                .into_iter()
                .filter_map(|(label, arg)| arg.map(|arg| (label, arg)))
            {
                out.push_str(&format!("    // {label} event: the handler stays quiet.\n"));
                out.push_str("    {\n");
                let call = dispatch_call(model, tys, Some(kind_arg));
                for binding in &call.bindings {
                    out.push_str(binding);
                    out.push('\n');
                }
                out.push_str(&call.call);
                out.push('\n');
                out.push_str("    }\n");
                out.push_str("    no_error(&id);\n");
            }
            let call = dispatch_call(model, tys, Some(plan.k1));
            for binding in &call.bindings {
                out.push_str(binding);
                out.push('\n');
            }
            out.push_str(&call.call);
            out.push('\n');
            for assert in rust_asserts(model, tys) {
                out.push_str(&assert);
                out.push('\n');
            }
            out.push_str("    no_error(&id);\n");
        }
    }
    out.push_str("}\n");
    out
}

/// One no-handler dispatch: the model only, no Lua work, outs unchanged.
fn quiet_block(model: &Model, tys: &BTreeMap<String, String>) -> String {
    let mut out = format!("    // {}: unregistered, nothing runs.\n", model.name);
    out.push_str("    {\n");
    let call = dispatch_call(model, tys, None);
    for binding in &call.bindings {
        out.push_str(binding);
        out.push('\n');
    }
    out.push_str(&call.call);
    out.push('\n');
    if model.contract == "cancel"
        && let Some(flag) = &model.cancel_flag
    {
        out.push_str(&format!(
            "    assert!(!{flag}, \"{flag} changed with no handler\");\n"
        ));
    }
    out.push_str("    }\n");
    out
}

/// One classification line of the checked-in record: every hook in exactly
/// one class, so `--check` fails when a hook is in no class or classified
/// differently from what the model says now.
fn class_line(name: &str, class: &Class) -> String {
    let detail = match class {
        Class::Generated(_) => "generated".to_owned(),
        Class::Adapter(whys) => format!("adapter: {}", whys.join("; ")),
        Class::Tick => "tick: a `ticks` parameter (level-tick host)".to_owned(),
        Class::Cannot(why) => format!("cannot: {why}"),
        Class::Handle(ty) => format!("handle: {name}: a {ty} handle needs its own design"),
        Class::Protocol => format!("protocol: {name}: raw packets need their own design"),
    };
    format!("    (\"{name}\", \"{detail}\"),")
}

/// `rustfmt` over generated text, as a string: what write mode leaves in
/// the tree after `cargo fmt`, so `--check` compares the same bytes.
fn format_snippet(text: &str) -> Result<String, String> {
    use std::io::Write;
    use std::process::Stdio;
    let mut child = std::process::Command::new("rustfmt")
        .args(["--edition", "2024"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .map_err(|e| format!("rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("rustfmt has no stdin")?
        .write_all(text.as_bytes())
        .map_err(|e| e.to_string())?;
    let out = child.wait_with_output().map_err(|e| e.to_string())?;
    if !out.status.success() {
        return Err(String::from_utf8_lossy(&out.stderr).into_owned());
    }
    String::from_utf8(out.stdout).map_err(|e| e.to_string())
}

pub fn run(check: bool) -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let classes = classify(&root)?;
    let (mut generated, mut adapter, mut tick, mut cannot, mut handle, mut protocol) =
        (0, 0, 0, 0, 0, 0);
    let mut kinded = 0;
    for hc in &classes {
        match &hc.class {
            Class::Generated(m) => {
                generated += 1;
                if !matches!(m.kind, Kind::None) {
                    kinded += 1;
                }
            }
            Class::Adapter(_) => adapter += 1,
            Class::Tick => tick += 1,
            Class::Cannot(_) => cannot += 1,
            Class::Handle(_) => handle += 1,
            Class::Protocol => protocol += 1,
        }
    }
    println!(
        "lua-hooks: {generated} generated ({kinded} kind-filtered), {adapter} adapter, {handle} handle, {protocol} protocol, {tick} tick-host, {cannot} cannot-be-exposed ({} total)",
        classes.len()
    );

    let mut names = Vec::new();
    let mut kind_names = Vec::new();
    let mut invocations = Vec::new();
    let mut tests = Vec::new();
    let mut quiet = Vec::new();
    for hc in &classes {
        let Class::Generated(model) = &hc.class else {
            continue;
        };
        let tys: BTreeMap<String, String> = model
            .dispatch_params
            .iter()
            .map(|p| (p.name.clone(), p.ty.clone()))
            .collect();
        names.push(model.name.clone());
        if !matches!(model.kind, Kind::None) {
            kind_names.push(model.name.clone());
        }
        invocations.push(invocation(model, &tys));
        if !SPIKE_HOOKS.contains(&model.name.as_str()) {
            tests.push(test_fn(model, &tys));
        }
        quiet.push(quiet_block(model, &tys));
    }

    let mut text = String::new();
    text.push_str(
        "//! The Lua side of every zero-hand-work native hook: one event table\n"
            .to_owned()
            .as_str(),
    );
    text.push_str(
        "//! per hook under the native name, over the hand-written runtime in\n//! `super::generated_runtime`. Do not edit: `cargo run -p xtask -- lua-hooks`\n//! regenerates this file, and `--check` fails when it is stale. Every\n//! native hook is classified exactly once below (`HOOK_CLASSIFICATION`),\n//! so a newly added native hook is either generated on re-run or fails the\n//! check naming it.\n\n",
    );
    text.push_str("/// Every native hook in exactly one class: `generated`, `adapter` +\n/// the missing converter, `tick` (the level-tick host), `cannot` + the\n/// reason. A new native hook lands here on re-run; `--check` fails until\n/// the file is regenerated, so the new hook is reviewed, not silently\n/// dropped. Only the classification test below reads it at runtime.\n");
    text.push_str("#[allow(dead_code)]\npub const HOOK_CLASSIFICATION: &[(&str, &str)] = &[\n");
    for hc in &classes {
        text.push_str(&class_line(&hc.name, &hc.class));
        text.push('\n');
    }
    text.push_str("];\n\n");
    text.push_str("#[cfg(test)]\nmod test_support;\n\n");
    text.push_str("#[cfg(test)]\nmod spike_tests;\n\n");
    text.push_str("#[cfg(test)]\nmod round3_tests;\n\n");
    text.push_str("/// The generated hooks, for `horizon.on`'s name check.\n");
    text.push_str("pub const GENERATED_HOOK_NAMES: &[&str] = &[\n");
    for name in &names {
        text.push_str(&format!("    \"{name}\",\n"));
    }
    text.push_str("];\n\n");
    text.push_str("/// The generated hooks whose `kind` filter runs: `horizon.on` rejects a\n/// kind for every other generated hook.\n");
    text.push_str("pub const GENERATED_KIND_HOOK_NAMES: &[&str] = &[\n");
    for name in &kind_names {
        text.push_str(&format!("    \"{name}\",\n"));
    }
    text.push_str("];\n\n");
    text.push_str("/// The `Hooks` methods: one macro invocation per hook (the table).\n");
    text.push_str("macro_rules! impl_generated_hooks {\n    () => {\n");
    for invocation in &invocations {
        text.push_str(invocation);
        text.push('\n');
    }
    text.push_str("    };\n}\n\n");
    text.push_str("#[cfg(test)]\nmod generated_tests {\n");
    text.push_str(
        "    use super::{GENERATED_HOOK_NAMES, GENERATED_KIND_HOOK_NAMES, HOOK_CLASSIFICATION};\n",
    );
    text.push_str("    use super::test_support::*;\n");
    text.push_str("    use horizon_client::mod_api::*;\n");
    text.push_str("    use horizon_client::menu::AnvilCraft;\n");
    text.push_str("    use horizon_client::merchant::ItemCost;\n");
    text.push_str("    use horizon_world::consumable::UseAnimation;\n");
    text.push_str("    use std::time::Duration;\n\n");
    text.push_str("    #[test]\n    fn generated_classification_names_every_hook_once() {\n");
    text.push_str("        let mut seen = std::collections::HashSet::new();\n");
    text.push_str("        for (name, _) in HOOK_CLASSIFICATION {\n");
    text.push_str("            assert!(seen.insert(*name), \"{name} classified twice\");\n");
    text.push_str("        }\n");
    text.push_str("        for name in GENERATED_HOOK_NAMES {\n");
    text.push_str("            assert!(\n");
    text.push_str("                seen.contains(name),\n");
    text.push_str("                \"{name} generated but not classified\"\n");
    text.push_str("            );\n");
    text.push_str("        }\n");
    text.push_str("        for name in GENERATED_KIND_HOOK_NAMES {\n");
    text.push_str("            assert!(\n");
    text.push_str("                GENERATED_HOOK_NAMES.contains(name),\n");
    text.push_str("                \"{name} kind-filtered but not generated\"\n");
    text.push_str("            );\n");
    text.push_str("        }\n");
    text.push_str("    }\n\n");
    for test in &tests {
        for line in test.lines() {
            text.push_str("    ");
            text.push_str(line);
            text.push('\n');
        }
        text.push('\n');
    }
    text.push_str("    #[test]\n    fn generated_no_handler_does_no_lua_work() {\n");
    text.push_str("        const LUA: &str = \"-- nothing registered\";\n");
    text.push_str("        let (m, id, dir) = loaded(\"gen_no_handler\", LUA);\n");
    text.push_str("        let firing_mods = boxed(m);\n");
    for block in &quiet {
        for line in block.lines() {
            text.push_str("    ");
            text.push_str(line);
            text.push('\n');
        }
    }
    text.push_str("        no_error(&id);\n");
    text.push_str("        drop_dir(dir);\n");
    text.push_str("    }\n");
    text.push_str("}\n");

    let path = root.join("crates/event-horizon-lua/src/generated_hooks/mod.rs");
    if check {
        let current = fs::read_to_string(&path).map_err(|e| e.to_string())?;
        // Write mode formats after writing, so the check formats too:
        // otherwise every file disagrees with its own fresh output.
        let formatted = format_snippet(&text)?;
        if current != formatted {
            return Err(
                "generated_hooks/mod.rs is stale: re-run `cargo run -p xtask -- lua-hooks`".into(),
            );
        }
        return Ok(());
    }
    fs::write(&path, text).map_err(|e| e.to_string())?;
    // Format like the rest of the tree; failure here is loud, not silent.
    let status = std::process::Command::new("cargo")
        .args([
            "fmt",
            "-p",
            "event-horizon-lua",
            "--",
            "crates/event-horizon-lua/src/generated_hooks/mod.rs",
        ])
        .status()
        .map_err(|e| e.to_string())?;
    if !status.success() {
        return Err("cargo fmt failed on the generated file".into());
    }
    Ok(())
}
