//! Generates the Lua side of every zero-hand-work native hook: one event
//! table per hook under the native name, cancel via `horizon.cancel()`,
//! mutable/collect/replace values read back, `Flow`/`Option` answers.
//!
//! The checked-in `generated_hooks.rs` is a compact table (one macro
//! invocation per hook: name, host kind, event type, kind filter, field
//! name -> converter) over the hand-written runtime in
//! `generated_runtime.rs`, plus a model-derived smoke test per hook. The
//! tool's other half is the classification: EVERY native hook lands in
//! exactly one class (`generated`, `adapter` + the missing converter,
//! `tick` for the level-tick host, `cannot` + the reason), recorded in the
//! output's `HOOK_CLASSIFICATION`. `--check` fails when a hook is in no
//! class, is classified differently from what the model says now, or the
//! checked-in output is stale: a newly added native hook with only
//! supported field types is generated by re-running the tool, and one with
//! an unsupported field fails the check naming it.

use crate::lua_model::{
    Class, Conv, Field, HookClass, Host, Kind, Model, ReplaceRead, assert_lines, canonical_elem,
    classify, deferred_outcomes, dup_leaf, lua_read, mutate_line, replace_sample, sample,
    table_leaves,
};
use std::{collections::BTreeMap, fs, path::Path};

// The smoke tests' kind filter: a zombie event fires zombie handlers only.
const KIND_ONE: &str = "minecraft:zombie";
const KIND_TWO: &str = "minecraft:skeleton";
// Entity ids the test host resolves: zombie, skeleton, gone.
const ENTITY_ONE: i64 = 11;
const ENTITY_TWO: i64 = 13;
const ENTITY_GONE: i64 = 99;

/// The macro's host kind for a model host.
fn host_ident(host: Host) -> &'static str {
    match host {
        Host::None => "none",
        Host::GameMut => "game_mut",
        Host::GameRef => "game_ref",
        Host::Level => "level",
        Host::LevelMut => "level_mut",
    }
}

/// The macro's kind filter for a model kind: one token tree, so the
/// contract macros take it as `$kind:tt`.
fn kind_tt(model: &Model) -> String {
    match &model.kind {
        Kind::None => "(none)".to_owned(),
        Kind::Field => "(field kind)".to_owned(),
        Kind::Entity { field, opt } => {
            if *opt {
                format!("(opt_entity {field})")
            } else {
                format!("(entity {field})")
            }
        }
        // Loot filters by the block id or entity kind of its context.
        Kind::Loot => "(loot)".to_owned(),
    }
}

/// Whether a `&mut` parameter's value lives in the event struct (the trait
/// copies scalar `&mut`s in): only then do the seed and write-back skip the
/// dereference.
fn owned_mut_scalar(ty: &str) -> bool {
    matches!(
        ty.strip_prefix("&mut ").unwrap_or(""),
        "bool"
            | "i8"
            | "i16"
            | "i32"
            | "i64"
            | "u8"
            | "u16"
            | "u32"
            | "u64"
            | "f32"
            | "f64"
            | "usize"
            | "isize"
            | "i128"
            | "u128"
            | "char"
    )
}

/// The macro's seed tag for a field: the tag names the runtime arm, the
/// type only picks among the shapes a converter covers. `ty` is the field's
/// canonical native type from the model, `key` the struct key for `Struct`.
fn seed_tag(conv: &Conv, ty: &str, key: Option<&str>) -> String {
    match conv {
        Conv::Plain => {
            if ty.contains("String") || ty.contains("str") {
                "cloned"
            } else {
                "copy"
            }
        }
        Conv::PlainString => "cloned",
        Conv::OptPlain => "copy",
        Conv::Uuid => "uuid",
        Conv::OptUuid => "opt_uuid",
        Conv::Player => "player",
        Conv::PlayerOpt => "player_opt",
        Conv::Dim => "dim",
        Conv::Pos => "pos",
        Conv::PosStruct => "pos_struct",
        Conv::OptPos => "opt_pos",
        Conv::Chunk => "chunk",
        Conv::Pair => {
            if ty.contains("f64") {
                "pair64"
            } else {
                "pair"
            }
        }
        Conv::Vec3f => "vec3",
        Conv::IntSeq => "int_seq",
        Conv::StrSeq => "str_seq",
        Conv::Item => "item",
        Conv::OptItem => "opt_item",
        Conv::StateLevel => "state_level",
        Conv::StateGame => "state_game",
        Conv::BlockAtPos => "block_at_pos",
        Conv::BlockFromState => "block_from_state",
        Conv::MutScalar => {
            if owned_mut_scalar(ty) {
                "copy"
            } else {
                "copy_ref"
            }
        }
        Conv::MutString => "mut_string",
        Conv::MutOptString => "mut_opt_string",
        Conv::MutPos => "mut_pos",
        Conv::MutVec3 => "mut_vec3",
        Conv::MutPair => {
            if ty.contains("f64") {
                "mut_pair64"
            } else {
                "mut_pair"
            }
        }
        Conv::MutStrVec => "str_seq",
        // The flat seeds ignore the field name and seed their table keys.
        Conv::LifecycleCtx => "lifecycle_ctx",
        Conv::TickPhase => "tick_phase",
        Conv::WorldPhaseName => "world_phase",
        Conv::LootCtx => "loot_ctx",
        // Loot's drops seed like the struct vec of stacks they are.
        Conv::LootDrops => return struct_shape(ty, key.unwrap_or("?")).0,
        Conv::Struct => return struct_shape(ty, key.unwrap_or("?")).0,
        Conv::Bytes => return "s_bytes".into(),
        Conv::PathStr => return "s_path".into(),
        Conv::TextVal => return "s_text".into(),
        Conv::TextOpt => return "s_opt_text".into(),
        Conv::PreLogin => return "s_defer".into(),
        Conv::StateProps => return "state_props_note".into(),
    }
    .to_owned()
}

/// The write-back tag for a mutable field: `None` transcribes no tag, and
/// the runtime's catch-all expands it to nothing. `ty` picks the dereference
/// like the seed does, `key` the struct shape for `Struct`.
fn write_tag(conv: &Conv, ty: &str, key: Option<&str>) -> Option<String> {
    match conv {
        Conv::MutScalar => Some(
            if owned_mut_scalar(ty) {
                "mut_scalar"
            } else {
                "mut_scalar_ref"
            }
            .to_owned(),
        ),
        Conv::MutString => Some("mut_string".into()),
        Conv::MutOptString => Some("mut_opt_string".into()),
        Conv::MutPos => Some("mut_pos".into()),
        Conv::MutVec3 => Some("mut_vec3".into()),
        Conv::MutPair => Some("mut_pair".into()),
        Conv::MutStrVec => Some(if ty.contains("str") {
            "mut_strvec_static".into()
        } else {
            "mut_strvec".into()
        }),
        // The component-keeping drops write-back, not a plain struct vec.
        Conv::LootDrops => Some("loot_write".into()),
        Conv::Struct => struct_shape(ty, key.unwrap_or("?")).1,
        Conv::TextVal => Some("w_text".into()),
        Conv::TextOpt => Some("w_opt_text".into()),
        Conv::PreLogin => Some("w_defer".into()),
        _ => None,
    }
}

/// The macro's replace reader for an out shape.
fn read_tag(read: ReplaceRead, ret: &str) -> String {
    match read {
        ReplaceRead::Int | ReplaceRead::Bool => "value".into(),
        ReplaceRead::Pair => "pair".into(),
        ReplaceRead::Item => "item".into(),
        ReplaceRead::Struct => {
            format!("struct_out({})", replace_spelling(ret))
        }
        ReplaceRead::StructVec => {
            format!("struct_vec_out({})", replace_spelling(ret))
        }
        ReplaceRead::Bytes => "bytes_out".into(),
        ReplaceRead::AnswerState => "answer_state".into(),
    }
}

/// The native spelling of a replace out's converted type, for the macro's
/// type parameter.
fn replace_spelling(ret: &str) -> String {
    let norm: String = ret.chars().filter(|c| !c.is_whitespace()).collect();
    let inner = norm
        .strip_prefix("Option<")
        .and_then(|k| k.strip_suffix('>'))
        .unwrap_or(&norm);
    let inner = inner
        .strip_prefix("Vec<")
        .and_then(|k| k.strip_suffix('>'))
        .unwrap_or(inner);
    struct_spelling_inner(inner)
}

/// The macro's type parameter for a struct key: the resolving path, since
/// the expansion site (the hand-written Lua mod) names only what it
/// imports. Tuples of primitives and arrays resolve on their own; the one
/// named tuple with imports uses the runtime alias.
fn struct_spelling_inner(inner: &str) -> String {
    match inner {
        "Value" => "serde_json::Value".to_owned(),
        "Map" => "serde_json::Map<String, serde_json::Value>".to_owned(),
        "(String,Compound)" => "crate::generated_runtime::NamedTag".to_owned(),
        "(&'staticstr,&'staticstr)" => "(&'static str, &'static str)".to_owned(),
        "&'staticstr" => "&'static str".to_owned(),
        "UseAnimation" => "horizon_world::consumable::UseAnimation".to_owned(),
        "Duration" => "std::time::Duration".to_owned(),
        "SocketAddr" => "std::net::SocketAddr".to_owned(),
        "ItemCost" => "horizon_client::merchant::ItemCost".to_owned(),
        "AnvilCraft" => "horizon_client::menu::AnvilCraft".to_owned(),
        _ if inner.starts_with('[') || inner.starts_with('&') || inner.starts_with('(') => {
            inner.to_owned()
        }
        _ => format!("horizon_client::mod_api::{inner}"),
    }
}

/// The seed and write-back tags of a struct field: the key's wrapper picks
/// the sequence arm, the parameter type's borrow the value arm, and the
/// inner type is the runtime's type parameter.
fn struct_shape(ty: &str, key: &str) -> (String, Option<String>) {
    let norm: String = ty.chars().filter(|c| !c.is_whitespace()).collect();
    let seed = |arm: &str, inner: &str| format!("{arm}({})", struct_spelling_inner(inner));
    let write = |arm: &str, inner: &str| Some(format!("{arm}({})", struct_spelling_inner(inner)));
    fn inner_of(key: &str) -> &str {
        if let Some(k) = key.strip_prefix("Vec<").and_then(|k| k.strip_suffix('>')) {
            return k;
        }
        if let Some(k) = key.strip_prefix("&[").and_then(|k| k.strip_suffix(']')) {
            return k;
        }
        if let Some(k) = key
            .strip_prefix("Option<")
            .and_then(|k| k.strip_suffix('>'))
        {
            return k;
        }
        key
    }
    if key.starts_with("Vec<") {
        let inner = inner_of(key);
        return (seed("s_vec", inner), write("w_vec", inner));
    }
    if key.starts_with("&[") {
        let inner = inner_of(key);
        return (seed("s_slice", inner), None);
    }
    if key.starts_with("Option<") {
        let inner = inner_of(key);
        if norm.starts_with("&mut") {
            return (seed("s_opt", inner), write("w_optmut", inner));
        }
        return (seed("s_opt", inner), None);
    }
    match key {
        "NativeMapInfo" => ("s_mapinfo".into(), None),
        "NativeNoteBlockChange" => ("s_notechange".into(), None),
        "SoundPlayback" => ("s_sound".into(), None),
        _ => {
            if norm.starts_with("&mut") {
                (seed("s_mut", key), write("w_mut", key))
            } else if norm.starts_with('&') {
                (seed("s_ref", key), None)
            } else {
                (seed("s_val", key), None)
            }
        }
    }
}

/// The event type with its elided lifetimes, exactly as the trait carries
/// it, qualified: the expansion site names only what it imports.
fn event_ty(model: &Model) -> String {
    format!(
        "horizon_client::mod_api::{}{}",
        model.event, model.lifetimes
    )
}

/// One hook's method invocation: the generated table's compact entry.
fn extra_tags(model: &Model) -> Vec<String> {
    model
        .extras
        .iter()
        .map(|e| format!("{}: {}", e.name, seed_tag(&e.conv, "?", None)))
        .collect()
}

fn invocation(model: &Model, tys: &BTreeMap<String, String>) -> String {
    // Three hooks run bespoke arms: the server tick suppresses unknown
    // phases and reloads on request, loot filters by its context's block or
    // entity with the absent-both early-out, and the data-pack collect runs
    // on every load including the first. Their fields still seed and write
    // back through the shared arms; only the dispatch shell is bespoke.
    let bespoke = match model.name.as_str() {
        "server_tick" => Some("gen_server_tick"),
        "loot_drops" => Some("gen_loot_drops"),
        "data_pack_files" => Some("gen_data_pack_files"),
        _ => None,
    };
    let contract = match model.contract.as_str() {
        "collect" => "gen_collect",
        "cancel" => "gen_cancel",
        "replace" => "gen_replace",
        _ => "gen_listen",
    };
    let mut tags: Vec<String> = model
        .fields
        .iter()
        .map(|f| {
            let ty = tys.get(&f.name).map(String::as_str).unwrap_or("?");
            let seed = seed_tag(&f.conv, ty, f.key.as_deref());
            match write_tag(&f.conv, ty, f.key.as_deref()) {
                Some(write) => format!("{}: {seed} => {write}", f.name),
                None => format!("{}: {seed}", f.name),
            }
        })
        .collect();
    tags.extend(extra_tags(model));
    let fields = tags.join(", ");
    // A bespoke arm keeps the kind token: it filters through it like the
    // stock arms do.
    let macro_name = bespoke.unwrap_or(contract);
    let mut out = format!(
        "    {macro_name}!({}, {}, {}, {}, [{fields}]",
        model.name,
        host_ident(model.host),
        event_ty(model),
        kind_tt(model),
    );
    if let Some(o) = &model.out {
        // The return type names the converted shape, so it resolves where
        // the hand-written mod expands the table (structs live in `mod_api`,
        // not in its imports).
        let ret = match o.read {
            ReplaceRead::Struct => format!("Option<{}>", replace_spelling(&o.ret)),
            ReplaceRead::StructVec => {
                format!("Option<Vec<{}>>", replace_spelling(&o.ret))
            }
            _ => o.ret.clone(),
        };
        out.push_str(&format!(
            ", {} : {}, {}",
            o.name,
            read_tag(o.read, &o.ret),
            ret
        ));
    }
    out.push_str(");");
    out
}

/// A dispatch argument set: the `let mut` bindings (`&mut` parameters and
/// outs) and the call line. `kind_rust` overrides the kind source's value
/// (K1, K2, or gone) for kind-filtered hooks.
struct Call {
    bindings: Vec<String>,
    call: String,
}

fn dispatch_call(
    model: &Model,
    tys: &BTreeMap<String, String>,
    kind_rust: Option<String>,
    flip_opt: bool,
) -> Call {
    let host_arg = match model.host {
        Host::None => String::new(),
        Host::GameMut => "&mut FakeHost::empty(), ".to_owned(),
        Host::GameRef => "&FakeHost::empty(), ".to_owned(),
        Host::Level => "&FakeLevel, ".to_owned(),
        Host::LevelMut => "&mut FakeLevel, ".to_owned(),
    };
    let mut bindings = Vec::new();
    let mut args = Vec::new();
    // Every native parameter in order; a non-collect out travels last.
    let mut params = model.dispatch_params.clone();
    if model.contract != "collect"
        && let Some(out) = &model.out
    {
        params.retain(|p| p.name != out.name);
    }
    for (n, param) in params.iter().enumerate() {
        let ty = param.ty.as_str();
        if Some(param.name.as_str()) == model.kind_field()
            && let Some(rust) = &kind_rust
        {
            args.push(rust.clone());
            continue;
        }
        if let Some(field) = model.fields.iter().find(|f| f.name == param.name) {
            let field_ty = tys.get(&field.name).map(String::as_str).unwrap_or(ty);
            let s = sample(
                &field.conv,
                field_ty,
                &field.name,
                eff_n(&field.conv, n, flip_opt),
            );
            if s.mutable {
                bindings.push(format!("    let mut {} = {};", param.name, s.rust));
                args.push(format!("&mut {}", param.name));
            } else if ty.trim_start().starts_with("&mut") {
                // A `&mut` sample with no write (an empty option): the
                // dispatch still needs a binding to borrow mutably.
                bindings.push(format!("    let mut {} = {};", param.name, s.rust));
                args.push(format!("&mut {}", param.name));
            } else {
                args.push(s.rust);
            }
        } else if model.skipped.contains(&param.name) {
            // The `name` a player table stands in for.
            args.push(sample(&Conv::Plain, ty, &param.name, n).rust);
        } else if ty.starts_with("BlockStateId") {
            // `is_bonemeal_success`'s `state`: kept out of the table (the
            // spike exposes it as `block`), still fired by dispatch.
            args.push(format!("BlockStateId({})", 8 + n));
        } else {
            args.push(format!("todo_{}", param.name));
        }
    }
    if model.contract == "cancel"
        && let Some(flag) = &model.cancel_flag
    {
        bindings.push(format!("    let mut {flag} = false;"));
        args.push(format!("&mut {flag}"));
    }
    if model.contract == "replace"
        && let Some(out) = &model.out
    {
        bindings.push(format!("    let mut {}: {} = None;", out.name, out.ret));
        args.push(format!("&mut {}", out.name));
    }
    let call = format!(
        "    dispatch_{}({host_arg}&firing_mods, {});",
        model.name,
        args.join(", ")
    );
    Call { bindings, call }
}

/// A kind-filtered test's firing plan: the K1/K2/gone dispatch arguments,
/// the kind the handler registers, and the kind the handler asserts (only a
/// `kind` string field asserts the kind; an entity id asserts its own
/// value through the normal field asserts).
struct KindPlan {
    k1: String,
    k2: String,
    gone: Option<String>,
    register: String,
    assert_kind: Option<String>,
}

fn kind_values(model: &Model) -> Option<KindPlan> {
    match &model.kind {
        Kind::None => None,
        Kind::Field => Some(KindPlan {
            k1: format!("\"{KIND_ONE}\""),
            k2: format!("\"{KIND_TWO}\""),
            gone: None,
            register: KIND_ONE.to_owned(),
            // The exact Lua literal, quotes included.
            assert_kind: Some(format!("\"{KIND_ONE}\"")),
        }),
        Kind::Entity { opt, .. } => {
            let (k1, k2) = if *opt {
                (format!("Some({ENTITY_ONE})"), format!("Some({ENTITY_TWO})"))
            } else {
                (ENTITY_ONE.to_string(), ENTITY_TWO.to_string())
            };
            let gone = if *opt {
                Some("None".to_owned())
            } else {
                Some(ENTITY_GONE.to_string())
            };
            Some(KindPlan {
                k1,
                k2,
                gone,
                register: KIND_ONE.to_owned(),
                // The entity id asserts as a number, without quotes.
                assert_kind: Some(ENTITY_ONE.to_string()),
            })
        }
        // Loot filters by the block id or entity kind of its context. K1
        // is the `n = 0` dispatch sample (a stone break), so the K1
        // firing's asserts match it exactly; K2 is a skeleton death, which
        // stays quiet; gone is neither block nor entity, the early-out.
        Kind::Loot => {
            let k1 = sample(&Conv::LootCtx, "&NativeLootDrops", "context", 0).rust;
            let k2 = "&horizon_client::test_events::native_loot_drops(\"test:tableK2\", \"minecraft:overworld\", [2.0, 64.0, 3.0], None, Some((13, \"minecraft:skeleton\")), None, None, None, false)".to_owned();
            let gone = "&horizon_client::test_events::native_loot_drops(\"test:tableGone\", \"minecraft:overworld\", [0.0, 64.0, 0.0], None, None, None, None, None, false)".to_owned();
            Some(KindPlan {
                k1,
                k2,
                gone: Some(gone),
                register: "minecraft:stone".to_owned(),
                assert_kind: Some("\"minecraft:stone\"".to_owned()),
            })
        }
    }
}

/// A dispatch field no generated test can assert deterministically: the
/// hook, the field, and the one-line reason. Anything missing from here
/// fails the generator (see `uncovered_fields`): a silent skip is a stale
/// test, not a passing one.
const FIELD_ALLOWLIST: &[(&str, &str, &str)] = &[];

fn allowlisted(hook: &str, field: &str) -> bool {
    FIELD_ALLOWLIST
        .iter()
        .any(|(h, f, _)| *h == hook && *f == field)
}

/// One dispatch parameter's Lua asserts: the kind line for the filtered
/// field, the converter's asserts otherwise. Empty means the field is
/// uncovered (see `uncovered_fields`).
fn param_asserts(
    model: &Model,
    field: &Field,
    ty: &str,
    n: usize,
    kind_lua: Option<&str>,
) -> Vec<String> {
    if Some(field.name.as_str()) == model.kind_field()
        && let Some(kind) = kind_lua
    {
        // Loot filters by the block id or entity kind of its context: the
        // kind line pins the block the K1 sample breaks, beside the full
        // flat asserts below.
        if model.kind == Kind::Loot {
            let mut lines = vec![format!("    assert(event.block.id == {kind}, \"kind\")")];
            let s = sample(&field.conv, ty, &field.name, n);
            lines.extend(assert_lines(
                &field.conv,
                &field.name,
                &s.lua,
                field.key.as_deref(),
                n,
            ));
            return lines;
        }
        return vec![format!(
            "    assert({} == {kind}, \"kind\")",
            lua_read(&field.name)
        )];
    }
    let s = sample(&field.conv, ty, &field.name, n);
    assert_lines(&field.conv, &field.name, &s.lua, field.key.as_deref(), n)
}

/// The sample index for one firing: the `_opt_item` test flips every OptItem
/// param to the other parity, so each optional stack is exercised both
/// present and absent across the hook's tests. Every other converter keeps
/// the dispatch index.
fn eff_n(conv: &Conv, n: usize, flip_opt: bool) -> usize {
    if flip_opt && matches!(conv, Conv::OptItem) {
        n + 1
    } else {
        n
    }
}

/// Whether `model` fires an optional stack: those hooks get a second test
/// with the option flipped, covering the state the dispatch index misses.
fn has_opt_item(model: &Model) -> bool {
    model.fields.iter().any(|f| matches!(f.conv, Conv::OptItem))
}

/// The hand-written spike test for `hook` in `spike_tests.rs`: the generator
/// scans it (instead of trusting it) for the player-`name` assert, so a spike
/// that drops the assert fails the check like a model test would.
fn spike_test_body<'a>(src: &'a str, hook: &str) -> Option<&'a str> {
    let start = src.find(&format!("\nfn generated_{hook}("))?;
    let rest = &src[start..];
    let end = rest[1..].find("\nfn ").map(|i| i + 1).unwrap_or(rest.len());
    Some(&rest[..end])
}

/// The Lua a spike test registers: the `r#"..."#` its `const LUA` wraps.
/// The gate scans Lua, not Rust source: Rust quoting (`r#"`, `\"`) would
/// misalign a comment stripper, hiding a bypass or inventing one.
fn spike_lua(body: &str) -> Option<&str> {
    let start = body.find("r#\"")? + 3;
    let rest = &body[start..];
    // The const ends `"#;`: a `"#` inside the Lua would end it early, so no
    // spike Lua may contain one (none does).
    let end = rest.find("\"#;")?;
    Some(&rest[..end])
}

/// The Lua tokens the spike-name gate reads: identifiers, single dots,
/// and `==`. Everything else (strings, comments, numbers, other
/// punctuation) is skipped, so the gate never sees text that is not code.
/// A run of two or more dots (`..`, `...`) yields no `Dot`: only a lone
/// `.` separates a table from its field.
#[derive(Debug, PartialEq, Eq)]
enum LuaTok {
    Ident(String),
    Dot,
    EqEq,
}

/// `src` as tokens, skipping strings and comments: short strings with
/// `\` escapes (an unterminated one runs to the end), long strings and
/// long comments of any `=` level, and `--` line comments. Identifiers
/// follow Lua's ASCII rule (letters, digits after the first, `_`).
fn lex_lua(src: &str) -> Vec<LuaTok> {
    let chars: Vec<char> = src.chars().collect();
    let mut toks = Vec::new();
    let mut i = 0;
    // A long bracket at `i`: `[` or `]` followed by `level` `=` and the
    // same bracket. Returns the level when `i` opens or closes one.
    let long_level = |i: usize, open: char, close: char| -> Option<usize> {
        if chars.get(i) != Some(&open) {
            return None;
        }
        let mut level = 0;
        while chars.get(i + 1 + level) == Some(&'=') {
            level += 1;
        }
        (chars.get(i + 1 + level) == Some(&close)).then_some(level)
    };
    while i < chars.len() {
        let c = chars[i];
        if c == '\'' || c == '"' {
            i += 1;
            while i < chars.len() {
                let d = chars[i];
                i += 1;
                if d == '\\' {
                    i += 1;
                } else if d == c {
                    break;
                }
            }
        } else if c == '['
            && let Some(level) = long_level(i, '[', '[')
        {
            i += 2 + level;
            while i < chars.len() && long_level(i, ']', ']') != Some(level) {
                i += 1;
            }
            i += 2 + level;
        } else if c == '-'
            && chars.get(i + 1) == Some(&'-')
            && let Some(level) = long_level(i + 2, '[', '[')
        {
            i += 4 + level;
            while i < chars.len() && long_level(i, ']', ']') != Some(level) {
                i += 1;
            }
            i += 2 + level;
        } else if c == '-' && chars.get(i + 1) == Some(&'-') {
            while i < chars.len() && chars[i] != '\n' {
                i += 1;
            }
        } else if c == '_' || c.is_ascii_alphabetic() {
            let start = i;
            while i < chars.len() && (chars[i] == '_' || chars[i].is_ascii_alphanumeric()) {
                i += 1;
            }
            toks.push(LuaTok::Ident(chars[start..i].iter().collect()));
        } else if c == '.' {
            let mut dots = 0;
            while chars.get(i + dots) == Some(&'.') {
                dots += 1;
            }
            if dots == 1 {
                toks.push(LuaTok::Dot);
            }
            i += dots;
        } else if c == '=' && chars.get(i + 1) == Some(&'=') {
            toks.push(LuaTok::EqEq);
            i += 2;
        } else if c.is_ascii_digit() {
            while i < chars.len()
                && (chars[i] == '_' || chars[i] == '.' || chars[i].is_ascii_alphanumeric())
            {
                i += 1;
            }
        } else {
            i += 1;
        }
    }
    toks
}

/// Whether `lua` asserts the player's name as code: the token sequence
/// `event` `.` <field> `.` `name` `==`. The token boundary is the whole
/// gate: text inside a string or comment never lexes to these tokens, and
/// a longer name (`not_the_event`, `names`) lexes to one identifier that
/// is not `event` or `name`.
fn lua_asserts_player_name(lua: &str, field: &str) -> bool {
    let toks = lex_lua(lua);
    toks.windows(6).any(|w| {
        matches!(&w[0], LuaTok::Ident(a) if a == "event")
            && w[1] == LuaTok::Dot
            && matches!(&w[2], LuaTok::Ident(b) if b == field)
            && w[3] == LuaTok::Dot
            && matches!(&w[4], LuaTok::Ident(c) if c == "name")
            && w[5] == LuaTok::EqEq
    })
}

/// The dispatch fields of `model` no assert covers: a parameter with no
/// field entry, or one whose Lua asserts are empty and which is not
/// allowlisted.
fn uncovered_fields(model: &Model, tys: &BTreeMap<String, String>, flip_opt: bool) -> Vec<String> {
    let kind_lua = kind_values(model)
        .as_ref()
        .and_then(|plan| plan.assert_kind.clone());
    let mut out = Vec::new();
    // Param order, so the samples match the dispatch call's: the `name`
    // a player table stands in for still takes its index.
    for (n, param) in model.dispatch_params.iter().enumerate() {
        if model.skipped.contains(&param.name) {
            continue;
        }
        let Some(field) = model.fields.iter().find(|f| f.name == param.name) else {
            if !allowlisted(&model.name, &param.name) {
                out.push(param.name.clone());
            }
            continue;
        };
        let ty = tys.get(&field.name).map(String::as_str).unwrap_or("?");
        let n = eff_n(&field.conv, n, flip_opt);
        if param_asserts(model, field, ty, n, kind_lua.as_deref()).is_empty()
            && !allowlisted(&model.name, &field.name)
        {
            out.push(field.name.clone());
        }
    }
    // The player `name` a player table stands in for is covered by that
    // table's asserts: a skipped `name` with no player table asserting it is
    // a silent hole, not a covered field.
    if model.skipped.iter().any(|s| s == "name")
        && !model
            .fields
            .iter()
            .any(|f| matches!(f.conv, Conv::Player | Conv::PlayerOpt))
    {
        out.push("name".to_owned());
    }
    // The table asserts the name only when its own `.name` line fires: a
    // player assert without it still passes a renamed dispatch, so every
    // player table must carry the name assert, whatever else it checks.
    for (n, param) in model.dispatch_params.iter().enumerate() {
        let Some(field) = model.fields.iter().find(|f| f.name == param.name) else {
            continue;
        };
        if !matches!(field.conv, Conv::Player | Conv::PlayerOpt) {
            continue;
        }
        let ty = tys.get(&field.name).map(String::as_str).unwrap_or("?");
        let n = eff_n(&field.conv, n, flip_opt);
        if !param_asserts(model, field, ty, n, kind_lua.as_deref())
            .iter()
            .any(|a| a.contains(".name =="))
        {
            out.push(format!("{}.name", field.name));
        }
    }
    out
}

/// A table leaf the emitted handler never asserts: the seed varies it, but
/// nothing fails when the runtime drops or changes it. `table_leaves` is the
/// model's own claim of what the handler checks, so every entry must appear
/// in the emitted asserts; a silent leaf is a stale test, not a passing one.
fn unasserted_leaves(model: &Model, tys: &BTreeMap<String, String>, flip_opt: bool) -> Vec<String> {
    let kind_lua = kind_values(model)
        .as_ref()
        .and_then(|plan| plan.assert_kind.clone());
    let mut out = Vec::new();
    for (n, param) in model.dispatch_params.iter().enumerate() {
        let Some(field) = model.fields.iter().find(|f| f.name == param.name) else {
            continue;
        };
        let ty = tys.get(&field.name).map(String::as_str).unwrap_or("?");
        let n = eff_n(&field.conv, n, flip_opt);
        let asserts = param_asserts(model, field, ty, n, kind_lua.as_deref());
        let lua = sample(&field.conv, ty, &field.name, n).lua;
        for (suffix, value) in table_leaves(&field.conv, &field.name, &lua, field.key.as_deref(), n)
        {
            let want = format!("{}{suffix} == {value}", lua_read(&field.name));
            if !asserts.iter().any(|a| a.contains(&want)) {
                out.push(format!("{}{suffix}", field.name));
            }
        }
    }
    out
}

/// The sequence row a leaf belongs to (`[1]`, `[2]`, ...): leaves of a plain
/// table share the empty row. Only a leading index counts as a row: a nested
/// one (a face list inside a container) is one table's leaf.
fn leaf_row(suffix: &str) -> &str {
    if suffix.starts_with('[')
        && let Some(end) = suffix.find("].")
    {
        &suffix[..end + 1]
    } else {
        ""
    }
}

/// A sequence leaf with its row prefix stripped (`[1].x` to `x`), so rows of
/// one sequence compare leaf by leaf.
fn row_leaf(suffix: &str) -> &str {
    if let Some(rest) = suffix.strip_prefix('[')
        && let Some(dot) = rest.find("].")
    {
        &suffix[dot + 3..]
    } else {
        suffix
    }
}

/// The asserted-value problems in one hook's fields: a repeated value inside
/// one row, or two identical sequence rows. Each names `hook: field` plus the
/// leaf (or row) to fix. One leaf per row is not coverage: a second assert of
/// the same value still passes when the handler never runs that leaf.
fn dup_values(model: &Model, tys: &BTreeMap<String, String>, flip_opt: bool) -> Vec<String> {
    let mut out = Vec::new();
    for (n, param) in model.dispatch_params.iter().enumerate() {
        let Some(field) = model.fields.iter().find(|f| f.name == param.name) else {
            continue;
        };
        let ty = tys.get(&field.name).map(String::as_str).unwrap_or("?");
        let n = eff_n(&field.conv, n, flip_opt);
        let lua = sample(&field.conv, ty, &field.name, n).lua;
        let leaves = table_leaves(&field.conv, &field.name, &lua, field.key.as_deref(), n);
        let mut rows: std::collections::BTreeMap<&str, Vec<(String, String)>> =
            std::collections::BTreeMap::new();
        for (suffix, value) in &leaves {
            rows.entry(leaf_row(suffix))
                .or_default()
                .push((suffix.clone(), value.clone()));
        }
        for (row, row_leaves) in &rows {
            if let Some(suffix) = dup_leaf(field.key.as_deref(), row_leaves) {
                let leaf = suffix.strip_prefix(row).unwrap_or(&suffix);
                out.push(format!("{}: {}{row}{leaf}", model.name, field.name));
            }
        }
        // Sequence rows must differ pairwise in at least one shared leaf:
        // two identical rows make reversing them pass. (`s_vec` shifts `n`
        // per element, so live rows always differ; a constant seed would not.)
        let seq: Vec<(&str, &Vec<(String, String)>)> = rows
            .iter()
            .filter(|(r, _)| !r.is_empty())
            .map(|(r, l)| (*r, l))
            .collect();
        for (i, (_, a)) in seq.iter().enumerate() {
            for (second, b) in &seq[..i] {
                let differs = a
                    .iter()
                    .any(|(s, v)| b.iter().any(|(t, w)| row_leaf(t) == row_leaf(s) && w != v));
                if !differs {
                    out.push(format!("{}: {}{second}", model.name, field.name));
                }
            }
        }
    }
    out
}

/// The handler body: an assert per field, the write-back edits, and the
/// cancel/replace answers.
fn handler_body(
    model: &Model,
    tys: &BTreeMap<String, String>,
    kind_lua: Option<&str>,
    cancel: bool,
    flip_opt: bool,
) -> String {
    // The handler-ran witness, read back from the mod's Lua state: a handler
    // whose asserts never fire leaves no error row, so without this a test
    // passes when the handler never runs at all.
    let mut lines = vec!["    __witness = (__witness or 0) + 1".to_owned()];
    // Param order, so the samples match the dispatch call's: the `name`
    // a player table stands in for still takes its index.
    let mut checked = false;
    for (n, param) in model.dispatch_params.iter().enumerate() {
        let Some(field) = model.fields.iter().find(|f| f.name == param.name) else {
            continue;
        };
        let ty = tys.get(&field.name).map(String::as_str).unwrap_or("?");
        let n = eff_n(&field.conv, n, flip_opt);
        let asserts = param_asserts(model, field, ty, n, kind_lua);
        checked |= !asserts.is_empty();
        lines.extend(asserts);
        let s = sample(&field.conv, ty, &field.name, n);
        if field.conv == Conv::LootDrops {
            // Loot's write-back keeps a same-id entry's stack (its
            // components): replacing the table with the write pair would
            // keep the seeds, not replace them. The generated test appends
            // a new stack instead, and the seeds keep their components
            // through the round trip; the replace, truncate, count-edit
            // and keep cases are the hand-written test's.
            lines.push(
                "    table.insert(event.drops, { id = \"test:drops:added\", count = 1 })"
                    .to_owned(),
            );
        } else if let Some(write) = s.write_lua {
            lines.push(mutate_line(&field.conv, &field.name, &write));
        }
    }
    if !checked {
        // A handler with nothing to check still proves the event exists.
        lines.push("    assert(event ~= nil, \"event\")".to_owned());
    }
    if cancel && model.contract == "cancel" {
        lines.push("    horizon.cancel()".to_owned());
    }
    if let Some(out) = &model.out {
        let (rust, lua) = replace_sample(out.read, &out.ret, 0);
        let _ = rust;
        lines.push(format!(
            "    assert(event.{} == nil, \"replace seed\")",
            out.name
        ));
        lines.push(format!("    event.{} = {lua}", out.name));
    }
    for extra in &model.extras {
        lines.extend(assert_lines(
            &extra.conv,
            &extra.name,
            "\"minecraft:stone\"",
            None,
            0,
        ));
    }
    lines.join("\n")
}

/// The Rust asserts after the K1 dispatch: outs and write-backs reached the
/// native side.
fn rust_asserts(model: &Model, tys: &BTreeMap<String, String>, flip_opt: bool) -> Vec<String> {
    let mut lines = Vec::new();
    if model.contract == "cancel"
        && let Some(flag) = &model.cancel_flag
    {
        lines.push(format!("    assert!({flag}, \"{flag} not cancelled\");"));
    }
    for (n, param) in model.dispatch_params.iter().enumerate() {
        let Some(field) = model.fields.iter().find(|f| f.name == param.name) else {
            continue;
        };
        let ty = tys.get(&field.name).map(String::as_str).unwrap_or("?");
        let n = eff_n(&field.conv, n, flip_opt);
        let s = sample(&field.conv, ty, &field.name, n);
        if field.conv == Conv::LootDrops {
            // The append above: the seeds round-trip untouched (their
            // components kept) with the new stack after them.
            let inner = s
                .rust
                .strip_prefix("vec![")
                .and_then(|s| s.strip_suffix(']'))
                .unwrap_or_else(|| panic!("no loot drops seed for {}", model.name));
            let added =
                "ItemStack { item: \"test:drops:added\".into(), count: 1, damage: 0, extra: None }";
            lines.push(format!(
                "    assert_eq!(format!(\"{{:?}}\", {}), format!(\"{{:?}}\", vec![{}, {}]));",
                field.name, inner, added
            ));
        } else if let Some(write) = s.write_rust {
            lines.push(match &field.conv {
                Conv::MutStrVec => format!(
                    "    assert_eq!({0}, vec![\"test:edited\".to_owned(), \"test:seed2\".to_owned(), \"test:added\".to_owned()]);",
                    field.name
                ),
                Conv::PreLogin => format!("    assert_eq!({}.len(), 1);", field.name),
                // A bare `true`/`false` is a bool write-back: `assert!` reads
                // better and keeps clippy's `bool_assert_comparison` quiet.
                _ if write == "true" => format!("    assert!({});", field.name),
                _ if write == "false" => format!("    assert!(!{});", field.name),
                // Sequences compare through `Debug`: not every element
                // implements `PartialEq` (a spawn entry has none).
                _ if write.starts_with("vec![") => format!(
                    "    assert_eq!(format!(\"{{:?}}\", {}), format!(\"{{:?}}\", {write}));",
                    field.name
                ),
                _ => format!("    assert_eq!({}, {write});", field.name),
            });
        }
    }
    if let Some(out) = &model.out
        && model.contract == "replace"
    {
        let (rust, lua) = replace_sample(out.read, &out.ret, 0);
        match out.read {
            ReplaceRead::Item => {
                lines.push(format!(
                    "    let replaced = {}.expect(\"a replaced value\");",
                    out.name
                ));
                lines.push("    assert_eq!(&*replaced.item, \"test:result\");".to_owned());
                lines.push("    assert_eq!(replaced.count, 1);".to_owned());
            }
            ReplaceRead::AnswerState => {
                let _ = rust;
                let _ = lua;
                let state_idx = model
                    .dispatch_params
                    .iter()
                    .position(|p| p.name == "state")
                    .unwrap_or(0);
                lines.push(format!(
                    "    assert_eq!({}, Some(Some(BlockStateId({}))));",
                    out.name,
                    8 + state_idx
                ));
            }
            _ => lines.push(format!("    assert_eq!({}, Some({rust}));", out.name)),
        }
    }
    lines
}

